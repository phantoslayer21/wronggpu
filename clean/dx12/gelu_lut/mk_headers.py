"""Writes hlsl/wg_gelu_lut.hlsli and runtime/gelu_lut_table.h from gen_compact.py outputs.

    python clean/dx12/gelu_lut/mk_headers.py --gen <dir with gelu_lut.json + gelu_lut_table.bin> [--gen2 <dir>]
        --hlsl clean/dx12/hlsl/wg_gelu_lut.hlsli --cpp clean/runtime/gelu_lut_table.h

--gen is the layout the kernels use by default (WG_GELU_LUT_ALT 0); --gen2 (optional, experiments only) adds a second
table right after the first one, selected in a shader by WG_GELU_LUT_ALT 1.
"""
import argparse
import json
import os

import numpy as np

HLSL = r"""// Exact q8(GELU(h)) of the MLP hidden path by a compact table lookup. GENERATED by clean/dx12/gelu_lut/mk_headers.py from
// gen_compact.py: do not edit.
//
// HIP (swin.co *_nc blocks, dec1_dec0__pack12.co, swin__bmegahg.co bneck6_nc) computes per hidden value h
//   g = h * rcp(1 + exp2(h * fma(h * h, -0.10029031, -2.30816186)))   (wg_platform.h wg_gelu, WG_GELU_MODE 2)
//   byte = v_cvt_pk_fp8_f32(g)                                         (wg_pack_q8_nc: no clamp)
// That byte is a fixed function of h with 204 changes over all 2^32 FP32 inputs. Here, without transcendentals:
//   w = fma(h, S, B);  c = f16_rtz(w)                 (v_fmaak_f32, v_cvt_pk_rtz_f16_f32 for two values)
@LAYOUT_DOC@
//   (a, b) = table[c >> 5];  byte = fp8(fma(h, a, b)) (one 8-byte load, v_fmac_f32, v_cvt_pk_fp8_f32)
// 32 slots per binade of w (K = 5). Inside a slot fma(h, a, b) is monotone, so (a, b) reproduces up to two steps of
// HIP's staircase, each placed to the ulp; S and B put both one-input flips (u = 0xbf6c7530, 0xbff0c85e) on slot
// boundaries. Valid whether the driver rounds fma(h, S, B) to FP32 before the conversion or folds both into one
// round-toward-zero conversion. Table: @SLOTS@ entries (a, b) float32 at arena byte offset WG_GELU_LUT_BASE (the runtime
// reserves and fills it, runtime/gelu_lut_table.h).
// Proven on the GPU against HIP for every FP32 bit pattern (gelu_lut/run.py --table): identical bytes for all 2^32
// inputs except FP32 denormal inputs (D3D12 flushes them).
//
// Use: hf = wg_gelu_q8_lut(h) for wg_pack_q8_nc(GELU(h)) of a v8f; or wg_gelu_lut_fetch8 early (the loads) and
// wg_gelu_lut_finish8 later (fma + conversion; wave-uniform control flow) to hide the load latency.
#pragma once

#ifndef WG_GELU_LUT_BASE
#define WG_GELU_LUT_BASE 256u
#endif
#ifndef WG_GELU_LUT_ALT
#define WG_GELU_LUT_ALT 0
#endif
@CONSTS@

// Byte offsets of the entries of two values from one packed conversion. The pre-mask drops the 5 low mantissa bits of
// both codes; its opaque bit 16 (0 at run time: wg_bid_ < 2^31) keeps the compiler from converting the first value a
// second time on its own for the low half's offset.
uint2 wg_gelu_lut_off2(float h0, float h1)
{
    const float w0 = mad(h0, WG_GELU_LUT_S, WG_GELU_LUT_B), w1 = mad(h1, WG_GELU_LUT_S, WG_GELU_LUT_B);
#if WG_GELU_LUT_CLAMP
    // codes clamped to the slots that matter: positive w to WG_GELU_LUT_HP, negative w to -WG_GELU_LUT_HN (RTZ
    // conversion first, then the clamp in FP16: the same codes as clamping the 16-bit codes; inf / NaN land on the
    // clamp slots)
    half2 c = half2((half)w0, (half)w1);
    c = max(min(c, half2(WG_GELU_LUT_HP, WG_GELU_LUT_HP)), half2(-WG_GELU_LUT_HN, -WG_GELU_LUT_HN));
    const uint d = ((uint)asuint16(c.x) | ((uint)asuint16(c.y) << 16)) & (0xffe0ffe0u | ((wg_bid_ >> 31) << 16));
#else
    const uint d = (f32tof16(w0) | (f32tof16(w1) << 16)) & (0xffe0ffe0u | ((wg_bid_ >> 31) << 16));
#endif
    return uint2(WG_GELU_LUT_TAB + ((d >> 2) & 0x7fffu), WG_GELU_LUT_TAB + (d >> 18));
}
// The value to convert: fp8(wg_gelu_lut_apply(h, e)) is HIP's byte (one fused v_fma_f32).
float wg_gelu_lut_apply(float h, uint2 e) { return mad(h, asfloat(e.x), asfloat(e.y)); }

struct wg_gelu_lut_e { uint2 e[8]; };
wg_gelu_lut_e wg_gelu_lut_fetch8(v8f h)
{
    wg_gelu_lut_e r;
    [unroll] for (uint i = 0; i < 4; ++i) {
        const uint2 o = wg_gelu_lut_off2(h.v[2 * i], h.v[2 * i + 1]);
        r.e[2 * i] = wg_mem.Load2(o.x);
        r.e[2 * i + 1] = wg_mem.Load2(o.y);
    }
    return r;
}
// FP8 bytes of 8 values from their entries (driver conversion: wave-uniform control flow).
uint2 wg_gelu_lut_finish8(v8f h, wg_gelu_lut_e t)
{
    v8f y;
    [unroll] for (uint i = 0; i < 8; ++i) y.v[i] = wg_gelu_lut_apply(h.v[i], t.e[i]);
    return wg_pack_q8_nc_ags(y);
}
// = HIP wg_pack_q8_nc(wg_gelu(h[0..7])) byte for byte.
uint2 wg_gelu_q8_lut(v8f h) { return wg_gelu_lut_finish8(h, wg_gelu_lut_fetch8(h)); }
"""

DOC = {
    "full": "//   slot = c >> 5 over all 2048 codes ([sign][exponent 5][5 mantissa bits]): no clamp",
    "clamp": "//   c clamped to [-HN, HP] (FP16 min / max of the pair): slot = [sign][exponent 3][5 mantissa bits]\n"
             "//   (the clamped codes never use the exponent's top two bits: two 2 KB halves, 8 KB apart)",
}


def f16_hex(code):
    return f"asfloat16((uint16_t)0x{code:04x}u)"


def consts(st, base_expr):
    lines = [f"#define WG_GELU_LUT_S asfloat(0x{int(st['S_bits'], 16):08x}u)   // {st['S']!r}",
             f"#define WG_GELU_LUT_B asfloat(0x{int(st['B_bits'], 16):08x}u)   // {st['B']!r}",
             f"#define WG_GELU_LUT_CLAMP {1 if st['layout'] == 'clamp' else 0}",
             f"#define WG_GELU_LUT_TAB ({base_expr})"]
    if st["layout"] == "clamp":
        lines += [f"#define WG_GELU_LUT_HP {f16_hex(st['hp'])}", f"#define WG_GELU_LUT_HN {f16_hex(st['hn'])}"]
    return lines


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--gen", required=True)
    ap.add_argument("--gen2")
    ap.add_argument("--hlsl", required=True)
    ap.add_argument("--cpp", required=True)
    a = ap.parse_args()
    st = json.load(open(os.path.join(a.gen, "gelu_lut.json")))
    tab = np.fromfile(os.path.join(a.gen, "gelu_lut_table.bin"), np.uint32)
    c = consts(st, "WG_GELU_LUT_BASE")
    doc = DOC[st["layout"]]
    if a.gen2:
        st2 = json.load(open(os.path.join(a.gen2, "gelu_lut.json")))
        tab2 = np.fromfile(os.path.join(a.gen2, "gelu_lut_table.bin"), np.uint32)
        c2 = consts(st2, f"WG_GELU_LUT_BASE + {4 * len(tab)}u")
        c = ["#if WG_GELU_LUT_ALT"] + c2 + ["#else"] + c + ["#endif"]
        doc += "\n//   (experiments: WG_GELU_LUT_ALT 1 selects the second table:)\n" + DOC[st2["layout"]]
        tab = np.concatenate([tab, tab2])
    text = HLSL.replace("@CONSTS@", "\n".join(c)).replace("@LAYOUT_DOC@", doc).replace("@SLOTS@", str(st["slots"]))
    with open(a.hlsl, "w", newline="\n") as f:
        f.write(text)
    # runtime copy: runs of equal (a, b) pairs
    w = tab.reshape(-1, 2)
    runs, i = [], 0
    while i < len(w):
        j = i
        while j + 1 < len(w) and w[j + 1, 0] == w[i, 0] and w[j + 1, 1] == w[i, 1]:
            j += 1
        runs.append((i, j - i + 1, int(w[i, 0]), int(w[i, 1])))
        i = j + 1
    lines = [f"    {{{s}, {n}, 0x{x:08x}u, 0x{y:08x}u}}," for s, n, x, y in runs]
    nb = 4 * len(tab)
    cpp = f"""// Exact q8(GELU) lookup table of the D3D12 MLP kernels (clean/dx12/hlsl/wg_gelu_lut.hlsli). GENERATED by
// clean/dx12/gelu_lut/mk_headers.py from gen_compact.py (HIP's exhaustive run-length form): do not edit. The D3D12
// devices reserve arena bytes [kGeluLutBase, kGeluLutBase + kGeluLutBytes) and fill them with gelu_lut_expand() at
// creation.
#pragma once
#include <cstddef>
#include <cstdint>

namespace wg {{
constexpr uint64_t kGeluLutBase = 256;       // = WG_GELU_LUT_BASE
constexpr size_t kGeluLutBytes = {nb};   // {len(w)} entries (a, b) of two float32
struct GeluLutRun {{ uint32_t first, count, a, b; }};
constexpr GeluLutRun kGeluLutRuns[] = {{
{chr(10).join(lines)}
}};
// Writes the {len(tab)} little-endian dwords of the table to out.
inline void gelu_lut_expand(uint32_t* out) {{
  for (const GeluLutRun& r : kGeluLutRuns)
    for (uint32_t i = 0; i < r.count; ++i) {{ out[2 * (r.first + i)] = r.a; out[2 * (r.first + i) + 1] = r.b; }}
}}
}}  // namespace wg
"""
    with open(a.cpp, "w", newline="\n") as f:
        f.write(cpp)
    tab.astype("<u4").tofile(os.path.join(os.path.dirname(os.path.abspath(a.gen)), "combined_table.bin"))
    print(a.hlsl, a.cpp, nb, "bytes", len(runs), "runs")


if __name__ == "__main__":
    main()
