def generate(text):
    s = text.replace("\r\n", "\n")

    def rep(old, new):
        nonlocal s
        n = s.count(old)
        if n != 1:
            sys.exit("fused_swin_gen.py: anchor found %d times in swin_block.hlsl (expected once):\n%s" % (n, old))
        s = s.replace(old, new)

    s = HDR + s[s.index('#include "wg_platform.hlsli"'):]
    rep(ARGS_OLD, ARGS_NEW)
    rep(ENTRY_OLD, ENTRY_NEW)
    rep(LOAD_OLD, LOAD_NEW)
    rep(XLD_OLD, XLD_NEW)
    rep(EXP_OLD, EXP_NEW)
    if not s.rstrip().endswith(STORE):
        sys.exit("fused_swin_gen.py: swin_block.hlsl no longer ends with the output store anchor:\n" + STORE)
    store = STORE[:-1].replace("    if (dst >= 0) {",
                               "    if (dst >= 0 && (SW_XE == 0 || FZ_KEEP_MAPS)) {   // xe: dec2.out only read by the expand")
    s = s.rstrip()[:-len(STORE)] + store + EPILOGUE + "\n"
    if s.count("@wg-kernel") != 6:
        sys.exit("fused_swin_gen.py: expected exactly the 6 fused @wg-kernel lines")
    return s


def main():
    s = generate(open(SRC, encoding="utf-8").read())
    old = open(DST, encoding="utf-8").read() if os.path.exists(DST) else None
    if old == s:
        print("fused_swin.hlsl up to date")
        return 0
    if "--check" in sys.argv:
        print("fused_swin.hlsl is STALE (run fused_swin_gen.py)")
        return 1
    with open(DST, "w", encoding="utf-8") as f:
        f.write(s)
    print("fused_swin.hlsl regenerated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
