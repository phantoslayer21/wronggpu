"""Generates fused_dec.hlsl (this directory) from the live dec1_dec0.hlsl: d1p12/swin_block_c64_add_dec0_xd_nc, the
fused dec1 + dec0 kernel launched WITHOUT the barrier after dec2's fused block (fusion xd, swin_block_c96_add_xe_xd_nc,
fused_swin.hlsl), so that its workgroups start while dec2's last workgroups still write e1.

    python clean/dx12/kernels/fused_dec_gen.py [--check]

build_dx12.py runs every fused_*_gen.py before it compiles. The kernel is dec1_dec0.hlsl text for text plus a wait: every
workgroup's thread 0 spins (bounded, as bneck.hlsl) until the dec2 window rows holding the e1 rows its windows gather
(mirrored at the borders) are complete (xd sync rows, counted by the xd kernel), then reads e1 with coherent loads.
The workgroup that passes its wait last (done counter = xd sync word 0) resets the rows: every row is waited on by some
workgroup, so every count has landed by then. Spin timeouts count in xd sync word 1. The generator replaces four anchors
of dec1_dec0.hlsl, each asserted unique; when an edit moves one, it stops with the anchor's text.
"""
import os
import sys

K = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(K, "dec1_dec0.hlsl")
DST = os.path.join(K, "fused_dec.hlsl")

HDR = """\
// GENERATED by fused_dec_gen.py from dec1_dec0.hlsl: do not edit (edit dec1_dec0.hlsl or the generator).
// d1p12/swin_block_c64_add_dec0_xd_nc (FZ_XD 1, fusion xd): d1p12/swin_block_c64_add_dec0_nc launched without the
// barrier after dec2's fused block swin_block_c96_add_xe_xd_nc: every workgroup first waits (thread 0, bounded spin)
// until the dec2 window rows of the e1 rows it gathers are complete (xd sync rows 16 ..), then reads e1 with coherent
// loads; the workgroup that passes its wait last resets the rows and the done counter (xd sync word 0). Same bytes.
// @wg-kernel d1p12/swin_block_c64_add_dec0_xd_nc co=dec1_dec0__pack12.co entry=swin_block_c64_add_dec0_nc block=256 wave=32 args=p,p,p,u,u,u,u,p,p,p,p,p,p,p,p,u,u,b56 defines=FZ_XD=1,WG_GELU_T5=0
"""

ARGS_OLD = """    uint a_motion, a_lprev, a_A, a_B, a_C, a_latent, a_wdec;
"""
ARGS_NEW = """    uint a_motion, a_lprev, a_A, a_B, a_C, a_latent, a_wdec;
    uint xd_sync;                                  // xd sync: word 0 done counter, 1 spin timeouts, 16 .. dec2's rows
    int xd_oy, xd_nwx;                             // dec2's window grid: y offset, windows per row
"""

KERNEL_OLD = """WG_KERNEL(swin_block_c64_add_dec0_nc)
"""
KERNEL_NEW = """#ifndef FZ_XD_SPIN_LIMIT
#define FZ_XD_SPIN_LIMIT (1u << 18)   // polls per row (bneck.hlsl BNECK_SPIN_LIMIT)
#endif
// Waits until e1 rows this workgroup gathers are final: its windows blk 8 .. blk 8 + 7 read rows mirror(4 wy - oy + i),
// i = 0 .. 3; e1 row e comes from dec2 token row e / 2, final when dec2's window row (e / 2 + xd_oy) / 4 has all xd_nwx
// windows counted. Then the workgroup barrier (device scope, as bneck.hlsl's waits).
void fz_wait_e1(int nwx, int nwin, uint tid)
{
    if (tid == 0u) {
        const int blk = (int)wg_block_id();
        const int w0 = blk * 8 < nwin ? blk * 8 : nwin - 1, w1 = blk * 8 + 7 < nwin ? blk * 8 + 7 : nwin - 1;
        const int a = 4 * (w0 / nwx) - a_oy, b = 4 * (w1 / nwx) - a_oy + 3;
        const int ma = wg_mirror(a, a_H), mb = wg_mirror(b, a_H);
        const int ca = a < 0 ? 0 : (a < a_H ? a : a_H - 1), cb = b < 0 ? 0 : (b < a_H ? b : a_H - 1);
        const int l0 = min(min(ma, mb), min(ca, cb)), l1 = max(max(ma, mb), max(ca, cb));
        const int q0 = ((l0 >> 1) + xd_oy) >> 2, q1 = ((l1 >> 1) + xd_oy) >> 2;
        [loop] for (int q = q0; q <= q1; ++q) {
            uint lim = 0, v;
            [loop] for (;;) {
                wg_mem_gc.InterlockedOr(xd_sync + 64u + (uint)q * 4u, 0u, v);
                if (v >= (uint)xd_nwx) break;
                if (++lim == FZ_XD_SPIN_LIMIT) {
                    wg_atomic_add(xd_sync, 4u, 1u);
                    break;
                }
            }
        }
        // the last workgroup past its wait: every row has been waited on and every count has landed
        if (wg_atomic_add(xd_sync, 0u, 1u) == wg_grid_ - 1u) {
            const int nq = (a_H / 2 + xd_oy + 3) >> 2;
            [loop] for (int r = 0; r < nq; ++r) wg_st32_gc(xd_sync, 64u + (uint)r * 4u, 0u);
            wg_st32_gc(xd_sync, 0u, 0u);
        }
    }
    wg_barrier();
}

WG_KERNEL(swin_block_c64_add_dec0_nc)
"""

GATHER_OLD = """    // Gather: token t of the window, mirrored at the borders."""
GATHER_NEW = """    fz_wait_e1(nwx, nwin, tid);
    // Gather: token t of the window, mirrored at the borders."""

LOAD_OLD = """        uint4 q0 = wg_ld128(a_x, src), q1 = wg_ld128(a_x, src + 16u);"""
LOAD_NEW = """        uint4 q0 = wg_mem_gc.Load4(a_x + src), q1 = wg_mem_gc.Load4(a_x + src + 16u);   // e1: coherent"""


def generate(text):
    s = text.replace("\r\n", "\n")

    def rep(old, new):
        nonlocal s
        n = s.count(old)
        if n != 1:
            sys.exit("fused_dec_gen.py: anchor found %d times in dec1_dec0.hlsl (expected once):\n%s" % (n, old))
        s = s.replace(old, new)

    s = HDR + s[s.index('#include "wg_platform.hlsli"'):]
    rep(ARGS_OLD, ARGS_NEW)
    rep(KERNEL_OLD, KERNEL_NEW)
    rep(GATHER_OLD, GATHER_NEW)
    rep(LOAD_OLD, LOAD_NEW)
    if s.count("@wg-kernel") != 1:
        sys.exit("fused_dec_gen.py: expected exactly the 1 fused @wg-kernel line")
    return s


def main():
    s = generate(open(SRC, encoding="utf-8").read())
    old = open(DST, encoding="utf-8").read() if os.path.exists(DST) else None
    if old == s:
        print("fused_dec.hlsl up to date")
        return 0
    if "--check" in sys.argv:
        print("fused_dec.hlsl is STALE (run fused_dec_gen.py)")
        return 1
    with open(DST, "w", encoding="utf-8") as f:
        f.write(s)
    print("fused_dec.hlsl regenerated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
