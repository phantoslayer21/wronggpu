"""Model M output-filter profiles of WrongGPU's own (runtime option output_filter), D/O = 1.5.

Spec 06's filter truncates the stretched Lanczos-3 kernel to 5 taps and renormalizes. With the +-1/4 pixel phase the
truncation is lopsided: the first moment of the 5 weights is 0.337 instead of 0.25, so even and odd output pixels are
taken at alternately shifted positions (pixel pairs unevenly spaced).

quality9  weights(): all 9 taps of the kernel's support, normalized, first moment corrected to 1/4. Its own kernel
          (post_filter_quality9*), not fused with the reconstruction.
quality5  weights5(): 5 taps, the footprint of spec 06's filter, so every post kernel (the fused ones included) runs
          unchanged with other constants, at the same cost: the least-squares fit of the ideal resampling filter
          (1/4 pixel delay below the output's Nyquist frequency, nothing above), weighted by a picture spectrum.

Only the final resampling changes; reconstruction, model parameters and both history representations are outside
this module.
"""
import numpy as np

from clean.reference import post


def weights():
    k = np.arange(-4, 5, dtype=np.float64)
    t = (k - 0.25) / 1.5
    w = np.where(np.abs(t) < 3.0, np.sinc(t) * np.sinc(t / 3.0), 0.0)
    w /= w.sum()
    # Minimum squared coefficient change subject to sum=1 and moment=1/4. sum(k)=0, sum(k^2)=60.
    w += ((0.25 - w @ k) / (k @ k)) * k
    return w


FIT_F0 = 0.02     # cycles per D pixel: weight 1 / (f^2 + FIT_F0^2) of the quality5 fit
FIT_POINTS = 501  # f = 0 ... 1/2, evenly spaced


def weights5():
    """quality5, even output phase, taps k = -2..2: minimizes sum over f of |H(f) - T(f)|^2 / (f^2 + FIT_F0^2) with
    sum(w) = 1, where H(f) = sum_k w_k exp(-2 pi i f k) and T is the ideal filter: exp(-2 pi i f / 4) (the 1/4 pixel
    delay of this phase) for f <= 1/3 cycle per D pixel (the output's Nyquist frequency), 0 above. The weight follows
    the spectrum of pictures (most energy at low frequencies), so the 5 taps follow the ideal phase where the picture
    has its edges and gradients. Solved in closed form (normal equations with one Lagrange multiplier)."""
    f = np.linspace(0.0, 0.5, FIT_POINTS)
    k5 = np.arange(-2, 3, dtype=np.float64)
    target = np.where(f <= 1.0 / 3.0, np.exp(-2j * np.pi * f * 0.25), 0.0)
    sw = 1.0 / np.sqrt(f * f + FIT_F0 * FIT_F0)
    e = np.exp(-2j * np.pi * f[:, None] * k5[None, :])
    a = np.concatenate([e.real * sw[:, None], e.imag * sw[:, None]])
    b = np.concatenate([target.real * sw, target.imag * sw])
    m = np.zeros((6, 6))
    m[:5, :5] = 2.0 * a.T @ a
    m[:5, 5] = m[5, :5] = 1.0
    return np.linalg.solve(m, np.concatenate([2.0 * a.T @ b, [1.0]]))[:5]


PROFILES = {"quality9": weights, "quality5": weights5}


def filter_pass(image, n_out, profile="quality9"):
    image = np.asarray(image, np.float64)
    we = PROFILES[profile]()
    half = len(we) // 2
    x = np.arange(n_out)
    center = 3 * (x // 2) + 2 * (x & 1)
    w = np.where((x & 1)[:, None] == 0, we[None, :], we[None, ::-1])
    idx = np.clip(center[:, None] + np.arange(-half, half + 1)[None, :], 0, len(image) - 1)
    taps = image[idx]
    value = (taps * w.reshape(w.shape + (1,) * (image.ndim - 1))).sum(axis=1)
    return post.clamp(value, taps.min(axis=1), taps.max(axis=1))


def encoded_filter(display, output_size, profile="quality9"):
    ow, oh = output_size
    image = np.asarray(display, np.float64)
    if image.shape != (post.recon_size_for(oh), post.recon_size_for(ow), 3):
        raise ValueError("the output-filter profiles require D = floor((3 O + 1)/2), three display channels")
    h = filter_pass(image.transpose(1, 0, 2), ow, profile).transpose(1, 0, 2)
    return filter_pass(h, oh, profile)


def output_filter(display, exposure, output_size, profile="quality9"):
    return (post.dec(encoded_filter(display, output_size, profile)) / post.exposure_or_one(exposure)).astype(np.float32)


def header5():
    """kernels/output_quality5.h: the quality5 weights rounded to FP32 (python -m clean.reference.output_quality
    [--check])."""
    w = weights5().astype(np.float32)
    names = ", ".join(float(v).hex() + "f" for v in w)
    return ("// quality5 output-filter weights, even output phase (odd: mirrored): generated by\n"
            "// clean/reference/output_quality.py (python -m clean.reference.output_quality) from its formula.\n"
            "#pragma once\n\nnamespace wg_quality5 {\nconstexpr float w[5] = {" + names + "};\n"
            "}  // namespace wg_quality5\n")


if __name__ == "__main__":
    import os
    import sys
    path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "kernels", "output_quality5.h")
    if "--check" in sys.argv:
        if open(path, newline="").read().replace("\r\n", "\n") != header5():
            raise SystemExit("kernels/output_quality5.h is not what weights5() gives")
        print("output_quality5.h matches weights5():", " ".join("%.9g" % v for v in weights5()))
    else:
        with open(path, "w", newline="\n") as fh:
            fh.write(header5())
        print("wrote", path)
