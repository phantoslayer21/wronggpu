"""GELU lookup tables of the second Swin design (kernels/swin_v2.hip), written by the clean team.

Correction table (WG_V2_GELU 3, the v2 default): GELU(x) = max(x, 0) - c(|x|) with c(a) = a Phi(-a) (0 <= c <= 0.17,
c -> 0 fast). Entry i of CTAB<M> is c at the midpoint of the FP16 bucket of positive numbers whose top 5 + M bits
(exponent, top M mantissa bits) are i, stored as FP16. The kernel computes y = clamp(x, 0, 448) - c in FP32 and
rounds y to FP8 once, so large |x| stay exact.

Direct table (WG_V2_GELU 4): entry i of GTAB<M> (with sign: top 6 + M bits) is q8(GELU(x_mid)) as an FP8 E4M3FN byte, where the FP16 numbers whose bit
pattern has the top bits i (sign, 5 exponent bits, the top M of the 10 mantissa bits) form the bucket [x_lo, x_hi]
and x_mid is its midpoint. The kernel converts a hidden pre-activation to FP16 rounding toward zero
(v_cvt_pk_rtz_f16_f32), takes the top 6 + M bits as the index and reads the FP8 byte from LDS. Buckets holding an
infinity or a NaN give 448 (positive) or 0 (negative); round toward zero never produces an infinity from a finite
value. A few entries that belong to FP16 NaN patterns only are stored as 0 (never read for finite inputs). The tables
are a fixed function of the spec's GELU (spec 02 step 9): no model data.

    python clean/runner/gelu_table.py            # rewrite clean/kernels/swin_v2_gelu_table.h
    python clean/runner/gelu_table.py --check    # exit 1 if the header differs from what this script writes
"""
import argparse
import math
import os
import sys

import numpy as np

_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
if _ROOT not in sys.path:
    sys.path.insert(0, _ROOT)

from clean.reference.fp8 import fp8_encode  # noqa: E402

HEADER = os.path.join(_ROOT, "clean", "kernels", "swin_v2_gelu_table.h")
CBITS = (7, 8)   # correction tables
GBITS = (8,)     # direct FP8 tables


def table(m):
    n = 1 << (6 + m)
    idx = np.arange(n, dtype=np.uint32)
    lo = (idx << (10 - m)).astype(np.uint16).view(np.float16).astype(np.float64)
    hi = ((idx << (10 - m)) + (1 << (10 - m)) - 1).astype(np.uint16).view(np.float16).astype(np.float64)
    out = np.empty(n, dtype=np.float64)
    for i in range(n):
        a, b = lo[i], hi[i]
        if not (math.isfinite(a) and math.isfinite(b)):
            neg = (int(idx[i]) >> (5 + m)) & 1
            out[i] = 0.0 if neg else 448.0
            continue
        x = 0.5 * (a + b)
        out[i] = min(0.5 * x * (1.0 + math.erf(x / math.sqrt(2.0))), 448.0)
    t = fp8_encode(out).astype(np.uint8)
    t[n // 2 - 4:n // 2] = 0  # NaN buckets only
    return t


def ctable(m):
    """FP16 bit patterns of c(a) = a Phi(-a) at the bucket midpoints (positive buckets only)."""
    n = 1 << (5 + m)
    idx = np.arange(n, dtype=np.uint32)
    lo = (idx << (10 - m)).astype(np.uint16).view(np.float16).astype(np.float64)
    hi = ((idx << (10 - m)) + (1 << (10 - m)) - 1).astype(np.uint16).view(np.float16).astype(np.float64)
    out = np.zeros(n, dtype=np.float64)
    for i in range(n):
        if math.isfinite(lo[i]) and math.isfinite(hi[i]):
            a = 0.5 * (lo[i] + hi[i])
            out[i] = a * 0.5 * math.erfc(a / math.sqrt(2.0))
    t = out.astype(np.float16).view(np.uint16)
    t[n - 2:] = 0  # NaN buckets only
    return t


def header_text():
    lines = ["// Generated by clean/runner/gelu_table.py (clean team; a fixed function of GELU, no model data). Do not edit.",
             "// WG_V2_CTAB<M>[i] = FP16 c(a) = a Phi(-a), a = midpoint of the positive FP16 bucket whose top 5 + M bits are i.",
             "// WG_V2_GTAB<M>[i] = q8(GELU(midpoint of the FP16 bucket whose top 6 + M bits are i)), FP8 E4M3FN bytes.",
             "#pragma once", ""]
    for m in CBITS:
        t = ctable(m)
        lines.append(f"#define WG_V2_CTAB{m}_BYTES {2 * len(t)}")
        lines.append(f"#define WG_V2_CTAB{m}_INIT \\")
        for r in range(0, len(t), 16):
            row = ",".join(f"0x{v:04x}" for v in t[r:r + 16])
            lines.append(f"  {row}{',' if r + 16 < len(t) else ''} \\")
        lines.append("")
    for m in GBITS:
        t = table(m)
        lines.append(f"#define WG_V2_GTAB{m}_BYTES {len(t)}")
        lines.append(f"#define WG_V2_GTAB{m}_INIT \\")
        for r in range(0, len(t), 32):
            row = ",".join(f"0x{v:02x}" for v in t[r:r + 32])
            lines.append(f"  {row}{',' if r + 32 < len(t) else ''} \\")
        lines.append("")
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = header_text()
    if args.check:
        with open(HEADER) as f:
            same = f.read() == text
        print("up to date" if same else "OUT OF DATE")
        return 0 if same else 1
    with open(HEADER, "w", newline="\n") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
