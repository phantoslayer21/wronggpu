"""Generate clean/rr_f/kernels/rr_elem_consts.hlsli: binary64 / double-double constants of the correctly rounded
f32 exp2, log2 used by the page-54b kernels (rr_exact_elem.hlsli). Mathematical constants only (Taylor and atanh
series coefficients, ln 2, 1/ln 2), computed here with 80-digit decimals and rounded to binary64.

Run: python -m clean.rr_f.gpu.gen_elem_consts   (rewrites the header; the committed header must match)."""
from decimal import Decimal, getcontext
from fractions import Fraction
from pathlib import Path
import math
import struct

getcontext().prec = 80
OUT = Path(__file__).resolve().parent.parent / "kernels" / "rr_elem_consts.hlsli"


def d64(x):
    """Nearest binary64 of a Decimal / Fraction (ties never occur for these irrational / long values)."""
    f = Fraction(x)
    v = float(f)                                # Python rounds Fraction -> float correctly (nearest even)
    return v


def words(v):
    lo, hi = struct.unpack("<II", struct.pack("<d", v))
    return f"asdouble(0x{lo:08x}u, 0x{hi:08x}u)"


def dd(x):
    hi = d64(x)
    lo = d64(Fraction(x) - Fraction(hi))
    return hi, lo


def main():
    ln2 = Decimal(2).ln()
    lines = ["// Generated by clean/rr_f/gpu/gen_elem_consts.py - do not edit.",
             "// Mathematical constants of the correctly rounded exp2 / log2 (rr_exact_elem.hlsli).", "#pragma once", ""]
    # exp2 fast path: 2^t = sum (ln2^k / k!) t^k, |t| <= 1/2, degree 13 (truncation < 2^-57)
    lines.append("double rr_exp2_c(uint k)\n{")
    for k in range(13, -1, -1):
        c = ln2 ** k / math.factorial(k)
        lines.append(f"    if (k == {k}u) return {words(d64(c))};")
    lines.append("    return 0.0;\n}")
    # exp in double-double: 1/k!, k = 0..24
    lines.append("void rr_inv_fact_dd(uint k, out double hi, out double lo)\n{")
    lines.append("    hi = 0.0; lo = 0.0;")
    for k in range(25):
        h, l = dd(Fraction(1, math.factorial(k)))
        lines.append(f"    if (k == {k}u) {{ hi = {words(h)}; lo = {words(l)}; }}")
    lines.append("}")
    h, l = dd(ln2)
    lines.append(f"#define RR_LN2_HI {words(h)}")
    lines.append(f"#define RR_LN2_LO {words(l)}")
    # log2 fast path: ln m = sum 2 s^(2k+1) / (2k+1), |s| <= 3 - 2 sqrt 2 < 0.1716, k = 0..12
    lines.append("double rr_log_c(uint k)\n{")
    for k in range(12, -1, -1):
        lines.append(f"    if (k == {k}u) return {words(d64(Fraction(2, 2 * k + 1)))};")
    lines.append("    return 0.0;\n}")
    h, l = dd(1 / ln2)
    lines.append(f"#define RR_INV_LN2_HI {words(h)}")
    lines.append(f"#define RR_INV_LN2_LO {words(l)}")
    text = "\n".join(lines) + "\n"
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(OUT)


if __name__ == "__main__":
    main()
