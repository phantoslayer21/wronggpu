"""Constants of the fast resolve's correctly rounded f32 exp2 (kernels/rr_resolve_fast_math.hlsli).

Mathematical constants only, computed exactly (80-digit decimals and fractions); every f32 is the nearest one (ties
never occur for these values):
  * kernels/rr_rf_tables.hlsli (written by this script): ln 2 as an f32 pair, 1/6, 1/24, the first-tier polynomial
    coefficients ln2^k / k!;
  * table(): T[j] = 2^(j/1024), j < 1024, as (hi, lo) f32 pairs (hi nearest to T, lo nearest to T - hi). The kernels
    compute it on the GPU once (rr_rf_init_table); gpu/resolve_fast.py probes compares that with table().

Run: python -m clean.rr_f.gpu.gen_rf_tables   (rewrites the header; the committed header must match)."""
from decimal import Decimal, getcontext
from fractions import Fraction
from pathlib import Path

import numpy as np

getcontext().prec = 80
OUT = Path(__file__).resolve().parent.parent / "kernels" / "rr_rf_tables.hlsli"
NT = 1024


def f32(x):
    """Nearest binary32 of an exact Fraction (normal range); asserts it is not a tie."""
    x = Fraction(x)
    c = np.float32(float(x))
    best = None
    for cand in (np.nextafter(c, np.float32(-np.inf)), c, np.nextafter(c, np.float32(np.inf))):
        d = abs(Fraction(float(cand)) - x)
        if best is None or d < best[0]:
            best = (d, cand)
        elif d == best[0]:
            raise SystemExit("tie")
    return np.float32(best[1])


def bits(v):
    return int(np.asarray(v, np.float32).view(np.uint32))


def table():
    """T[j] = 2^(j/1024) as 2048 uint32 words: word 2j = bits(hi), 2j + 1 = bits(lo)."""
    words = []
    for j in range(NT):
        t = Fraction(Decimal(2) ** (Decimal(j) / Decimal(NT)))
        hi = f32(t)
        lo = f32(t - Fraction(float(hi))) if t != Fraction(float(hi)) else np.float32(0)
        words += [bits(hi), bits(lo)]
    return np.array(words, np.uint32)


def main():
    ln2 = Fraction(Decimal(2).ln())
    lines = ["// Generated by clean/rr_f/gpu/gen_rf_tables.py - do not edit.",
             "// Constants of the fast correctly rounded f32 exp2 (rr_resolve_fast_math.hlsli): ln 2 = RF_L1 + RF_L2;",
             "// 1/6, 1/24; RF_Pk = ln2^k / k!. The table 2^(j/1024) is computed on the GPU (rr_rf_init_table).",
             "#pragma once", ""]
    l1 = f32(ln2)
    l2 = f32(ln2 - Fraction(float(l1)))
    lines.append(f"#define RF_L1 asfloat(0x{bits(l1):08x}u)   // {float(l1)!r}")
    lines.append(f"#define RF_L2 asfloat(0x{bits(l2):08x}u)   // {float(l2)!r}")
    lines.append(f"#define RF_C3 asfloat(0x{bits(f32(Fraction(1, 6))):08x}u)")
    lines.append(f"#define RF_C4 asfloat(0x{bits(f32(Fraction(1, 24))):08x}u)")
    lines.append(f"#define RF_NT {NT}u")
    # first-tier polynomial 2^r - 1 ~ r (P1 + r (P2 + r P3)): P_k = RN(ln2^k / k!)
    for k, c in ((1, ln2), (2, ln2 ** 2 / 2), (3, ln2 ** 3 / 6)):
        lines.append(f"#define RF_P{k} asfloat(0x{bits(f32(c)):08x}u)")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
