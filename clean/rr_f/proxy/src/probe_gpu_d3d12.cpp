// DXGI format families (public DXGI_FORMAT numbers): typeless member, float, unorm, snorm, sRGB, depth members.
struct Family { uint32_t typeless, flt, unorm, snorm, srgb, depth; };
const Family kFamilies[] = {
    {DXGI_FORMAT_R32G32B32A32_TYPELESS, DXGI_FORMAT_R32G32B32A32_FLOAT, 0, 0, 0, 0},
    {DXGI_FORMAT_R32G32B32_TYPELESS, DXGI_FORMAT_R32G32B32_FLOAT, 0, 0, 0, 0},
    {DXGI_FORMAT_R16G16B16A16_TYPELESS, DXGI_FORMAT_R16G16B16A16_FLOAT, DXGI_FORMAT_R16G16B16A16_UNORM,
     DXGI_FORMAT_R16G16B16A16_SNORM, 0, 0},
    {DXGI_FORMAT_R32G32_TYPELESS, DXGI_FORMAT_R32G32_FLOAT, 0, 0, 0, 0},
    {DXGI_FORMAT_R32G8X24_TYPELESS, DXGI_FORMAT_R32_FLOAT_X8X24_TYPELESS, 0, 0, 0, DXGI_FORMAT_D32_FLOAT_S8X24_UINT},
    {DXGI_FORMAT_R10G10B10A2_TYPELESS, 0, DXGI_FORMAT_R10G10B10A2_UNORM, 0, 0, 0},
    {DXGI_FORMAT_R8G8B8A8_TYPELESS, 0, DXGI_FORMAT_R8G8B8A8_UNORM, DXGI_FORMAT_R8G8B8A8_SNORM,
     DXGI_FORMAT_R8G8B8A8_UNORM_SRGB, 0},
    {DXGI_FORMAT_R16G16_TYPELESS, DXGI_FORMAT_R16G16_FLOAT, DXGI_FORMAT_R16G16_UNORM, DXGI_FORMAT_R16G16_SNORM, 0, 0},
    {DXGI_FORMAT_R32_TYPELESS, DXGI_FORMAT_R32_FLOAT, 0, 0, 0, DXGI_FORMAT_D32_FLOAT},
    {DXGI_FORMAT_R24G8_TYPELESS, 0, DXGI_FORMAT_R24_UNORM_X8_TYPELESS, 0, 0, DXGI_FORMAT_D24_UNORM_S8_UINT},
    {DXGI_FORMAT_R8G8_TYPELESS, 0, DXGI_FORMAT_R8G8_UNORM, DXGI_FORMAT_R8G8_SNORM, 0, 0},
    {DXGI_FORMAT_R16_TYPELESS, DXGI_FORMAT_R16_FLOAT, DXGI_FORMAT_R16_UNORM, DXGI_FORMAT_R16_SNORM, 0,
     DXGI_FORMAT_D16_UNORM},
    {DXGI_FORMAT_R8_TYPELESS, 0, DXGI_FORMAT_R8_UNORM, DXGI_FORMAT_R8_SNORM, 0, 0},
    {DXGI_FORMAT_B8G8R8A8_TYPELESS, 0, DXGI_FORMAT_B8G8R8A8_UNORM, 0, DXGI_FORMAT_B8G8R8A8_UNORM_SRGB, 0},
    {DXGI_FORMAT_B8G8R8X8_TYPELESS, 0, DXGI_FORMAT_B8G8R8X8_UNORM, 0, DXGI_FORMAT_B8G8R8X8_UNORM_SRGB, 0},
};

const Family* family_of(uint32_t f) {
  if (!f) return nullptr;
  for (const Family& m : kFamilies)
    if (f == m.typeless || f == m.flt || f == m.unorm || f == m.snorm || f == m.srgb || f == m.depth) return &m;
  return nullptr;
}

bool is_typeless(uint32_t f) {
  const Family* m = family_of(f);
  return m && f == m->typeless;
}

bool is_depth(uint32_t f) {
  const Family* m = family_of(f);
  return m && m->depth && f == m->depth;
}

// A typed, readable member of the same family (not the typeless or a depth member).
bool typed_member(const Family* m, uint32_t f) {
  return m && f && (f == m->flt || f == m->unorm || f == m->snorm || f == m->srgb);
}

