constexpr UINT kHeapSize = 256;      // descriptors; a pair per pass, reused after 128 passes (>> frames in flight)
constexpr UINT kPatchSlots = 64;     // readback slots of 32 bytes
constexpr UINT kSlotBytes = 32;

template <typename T>
void release(T*& p) {
  if (p) p->Release();
  p = nullptr;
}

D3D12_RESOURCE_BARRIER transition(ID3D12Resource* r, D3D12_RESOURCE_STATES from, D3D12_RESOURCE_STATES to) {
  D3D12_RESOURCE_BARRIER b = {};
  b.Type = D3D12_RESOURCE_BARRIER_TYPE_TRANSITION;
  b.Transition.pResource = r;
  b.Transition.Subresource = D3D12_RESOURCE_BARRIER_ALL_SUBRESOURCES;
  b.Transition.StateBefore = from;
  b.Transition.StateAfter = to;
  return b;
}

std::string num(uint64_t v) { return std::to_string(v); }

// ---- capture option: files next to the game executable (CAPTURE.md) ----------------------------------------------

std::wstring exe_dir() {
  wchar_t buf[MAX_PATH * 2];
  DWORD n = GetModuleFileNameW(nullptr, buf, (DWORD)(sizeof buf / sizeof buf[0]));
  std::wstring p(buf, n);
  size_t slash = p.find_last_of(L"\\/");
  return slash == std::wstring::npos ? std::wstring() : p.substr(0, slash + 1);
}

std::wstring widen(const std::string& s) {
  if (s.empty()) return std::wstring();
  int n = MultiByteToWideChar(CP_UTF8, 0, s.c_str(), (int)s.size(), nullptr, 0);
  std::wstring w(n, L'\0');
  MultiByteToWideChar(CP_UTF8, 0, s.c_str(), (int)s.size(), &w[0], n);
  return w;
}

std::string narrow(const std::wstring& w) {
  if (w.empty()) return std::string();
  int n = WideCharToMultiByte(CP_UTF8, 0, w.c_str(), (int)w.size(), nullptr, 0, nullptr, nullptr);
  std::string s(n, '\0');
  WideCharToMultiByte(CP_UTF8, 0, w.c_str(), (int)w.size(), &s[0], n, nullptr, nullptr);
  return s;
}

// The probe settings file and the capture folder live next to the game executable (bin\x64 for the supported games,
// the hook build's data directory). Files are written by one worker thread in the order given (frame.json last), each
// under a temporary name renamed when complete.
class FileCaptureHost : public ProbeCaptureHost {
 public:
  ~FileCaptureHost() override {
    {
      std::lock_guard<std::mutex> lock(mu_);
      stop_ = true;
    }
    cv_.notify_all();
    if (worker_.joinable()) worker_.join();
  }

  bool read_settings(std::string* text) override {
    const std::wstring p = exe_dir() + L"wronggpu-rr-probe.ini";
    FILE* f = _wfopen(p.c_str(), L"rb");
    if (!f) return false;
    char buf[4096];
    size_t n;
    text->clear();
    while ((n = fread(buf, 1, sizeof buf, f)) > 0 && text->size() < (1u << 20)) text->append(buf, n);
    fclose(f);
    return true;
  }

  void set_folder(const std::string& path) override {
    std::lock_guard<std::mutex> lock(mu_);
    folder_ = widen(path);
    while (!folder_.empty() && (folder_.back() == L'\\' || folder_.back() == L'/')) folder_.pop_back();
  }

  bool open(std::string* where) override {
    std::lock_guard<std::mutex> lock(mu_);
    if (!opened_) {
      opened_ = true;
      base_ = folder_.empty() ? exe_dir() + L"wronggpu-rr-capture" : folder_;
      if (GetFileAttributesW(base_.c_str()) != INVALID_FILE_ATTRIBUTES) {
        SYSTEMTIME t;
        GetLocalTime(&t);
        wchar_t sfx[40];
        swprintf(sfx, 40, L"%04u%02u%02u-%02u%02u%02u", t.wYear, t.wMonth, t.wDay, t.wHour, t.wMinute, t.wSecond);
        const std::wstring old = base_ + L"." + sfx;
        if (MoveFileExW(base_.c_str(), old.c_str(), 0)) renamed_ = old;  // an earlier run's capture is kept
        else base_ += std::wstring(L"-") + sfx;                          // cannot rename: a new folder instead
      }
      ok_ = CreateDirectoryW(base_.c_str(), nullptr) != 0 || GetLastError() == ERROR_ALREADY_EXISTS;
    }
    *where = narrow(base_) + (renamed_.empty() ? "" : " (the earlier capture was renamed to " + narrow(renamed_) + ")");
    return ok_;
  }

  bool write(const std::string& rel_path, std::vector<uint8_t>&& data) override {
    std::lock_guard<std::mutex> lock(mu_);
    if (!ok_ || stop_) return false;
    queue_.push_back(Item{rel_path, std::move(data)});
    if (!worker_.joinable()) worker_ = std::thread([this] { run(); });
    cv_.notify_all();
    return true;
  }

  uint64_t flush() override {
    std::unique_lock<std::mutex> lock(mu_);
    idle_.wait(lock, [this] { return queue_.empty() && !busy_; });
    return failed_;
  }

 private:
  struct Item {
    std::string rel;
    std::vector<uint8_t> data;
  };

  void run() {
    std::unique_lock<std::mutex> lock(mu_);
    for (;;) {
      cv_.wait(lock, [this] { return stop_ || !queue_.empty(); });
      if (queue_.empty()) return;  // stopping
      Item it = std::move(queue_.front());
      queue_.pop_front();
      busy_ = true;
      lock.unlock();
      const bool ok = write_now(it);
      lock.lock();
      busy_ = false;
      if (!ok) ++failed_;
      if (queue_.empty()) idle_.notify_all();
    }
  }

  bool write_now(const Item& it) {
    std::wstring path = base_;
    size_t a = 0;
    for (;;) {
      size_t s = it.rel.find('/', a);
      if (s == std::string::npos) break;
      path += L"\\" + widen(it.rel.substr(a, s - a));
      CreateDirectoryW(path.c_str(), nullptr);
      a = s + 1;
    }
    path += L"\\" + widen(it.rel.substr(a));
    const std::wstring part = path + L".part";
    FILE* f = _wfopen(part.c_str(), L"wb");
    if (!f) return false;
    const bool ok = it.data.empty() || fwrite(it.data.data(), 1, it.data.size(), f) == it.data.size();
    const bool closed = fclose(f) == 0;
    return ok && closed && MoveFileExW(part.c_str(), path.c_str(), MOVEFILE_REPLACE_EXISTING);
  }

  std::mutex mu_;
  std::condition_variable cv_, idle_;
  std::deque<Item> queue_;
  std::thread worker_;
  bool opened_ = false, ok_ = false, stop_ = false, busy_ = false;
  uint64_t failed_ = 0;
  std::wstring base_, renamed_, folder_;
};

class D3d12ProbeGpu : public ProbeGpu {
 public:
  ~D3d12ProbeGpu() override { reset(); }

  void set_device(void* native_device) override {
    std::lock_guard<std::mutex> lock(mu_);
    ID3D12Device* d = nullptr;
    if (native_device)
      static_cast<IUnknown*>(native_device)->QueryInterface(__uuidof(ID3D12Device), reinterpret_cast<void**>(&d));
    if (d == dev_) {
      release(d);
      return;
    }
    reset();
    dev_ = d;
  }

  bool has_device() const override { return dev_ != nullptr; }

  bool describe(void* resource, ProbeTexDesc* out) override {
    if (!resource) return false;
    ID3D12Resource* r = nullptr;
    if (FAILED(static_cast<IUnknown*>(resource)->QueryInterface(__uuidof(ID3D12Resource),
                                                                reinterpret_cast<void**>(&r))))
      return false;
    D3D12_RESOURCE_DESC d = r->GetDesc();
    r->Release();
    out->dimension = (uint32_t)d.Dimension;
    out->format = (uint32_t)d.Format;
    out->width = (uint32_t)d.Width;
    out->height = d.Height;
    out->depth_or_array = d.DepthOrArraySize;
    out->mips = d.MipLevels;
    out->samples = d.SampleDesc.Count;
    out->flags = (uint32_t)d.Flags;
    return true;
  }

  WgResultCode upscale(void* native_cmd, const ProbeView& src, const ProbeView& dst, std::string* why) override {
    std::lock_guard<std::mutex> lock(mu_);
    if (!ensure(why)) return WG_E_COMPUTE_FAILED;
    ID3D12GraphicsCommandList* cl = command_list(native_cmd, why);
    if (!cl) return WG_E_COMPUTE_FAILED;
    WgResultCode rc = record_upscale(cl, src, dst, why);
    cl->Release();
    return rc;
  }

  WgResultCode patch_mean(void* native_cmd, const ProbeView& src, uint32_t px, uint32_t py, uint32_t slot,
                          uint32_t marker, std::string* why) override {
    std::lock_guard<std::mutex> lock(mu_);
    if (slot >= kPatchSlots) { *why = "slot out of range"; return WG_E_INVALID_PARAMETER; }
    if (!ensure(why)) return WG_E_COMPUTE_FAILED;
    ID3D12GraphicsCommandList* cl = command_list(native_cmd, why);
    if (!cl) return WG_E_COMPUTE_FAILED;
    WgResultCode rc = record_patch(cl, src, px, py, slot, marker, why);
    cl->Release();
    return rc;
  }

  bool read_patch(uint32_t slot, uint32_t marker, float mean[4]) override {
    std::lock_guard<std::mutex> lock(mu_);
    if (!readback_ || slot >= kPatchSlots) return false;
    D3D12_RANGE r = {slot * kSlotBytes, (slot + 1) * kSlotBytes};
    void* p = nullptr;
    if (FAILED(readback_->Map(0, &r, &p)) || !p) return false;
    const uint8_t* b = static_cast<const uint8_t*>(p) + slot * kSlotBytes;
    uint32_t m = 0, count = 0;
    memcpy(&m, b + 16, 4);
    memcpy(&count, b + 20, 4);
    bool ok = m == marker && count == 256;
    if (ok) memcpy(mean, b, 16);
    D3D12_RANGE none = {0, 0};
    readback_->Unmap(0, &none);
    return ok;
  }

  void* copy_input(void* native_cmd, const ProbeView& src, uint32_t key, uint32_t* copy_state,
                   std::string* why) override {
    std::lock_guard<std::mutex> lock(mu_);
    if (!dev_) { *why = "no D3D12 device"; return nullptr; }
    if (src.state == 0xffffffffu) { *why = "resource state not given"; return nullptr; }
    ID3D12Resource* s = resource(src.resource);
    if (!s) { *why = "not a D3D12 resource"; return nullptr; }
    D3D12_RESOURCE_DESC d = s->GetDesc();
    if (d.Dimension != D3D12_RESOURCE_DIMENSION_TEXTURE2D || d.SampleDesc.Count != 1) {
      s->Release();
      *why = "not a single-sample 2D texture";
      return nullptr;
    }
    Copy& c = copies_[key];
    D3D12_RESOURCE_DESC want = d;
    want.Flags = D3D12_RESOURCE_FLAG_NONE;
    if (c.tex) {
      D3D12_RESOURCE_DESC have = c.tex->GetDesc();
      if (have.Width != want.Width || have.Height != want.Height || have.Format != want.Format ||
          have.MipLevels != want.MipLevels || have.DepthOrArraySize != want.DepthOrArraySize) {
        retired_.push_back(c.tex);  // may still be read by frames in flight: kept until the device changes
        c.tex = nullptr;
      }
    }
    if (!c.tex) {
      D3D12_HEAP_PROPERTIES hp = {};
      hp.Type = D3D12_HEAP_TYPE_DEFAULT;
      if (FAILED(dev_->CreateCommittedResource(&hp, D3D12_HEAP_FLAG_NONE, &want,
                                               D3D12_RESOURCE_STATE_NON_PIXEL_SHADER_RESOURCE, nullptr,
                                               __uuidof(ID3D12Resource), reinterpret_cast<void**>(&c.tex)))) {
        s->Release();
        *why = "copy texture not created";
        return nullptr;
      }
    }
    ID3D12GraphicsCommandList* cl = command_list(native_cmd, why);
    if (!cl) {
      s->Release();
      return nullptr;
    }
    const D3D12_RESOURCE_STATES declared = (D3D12_RESOURCE_STATES)src.state;
    D3D12_RESOURCE_BARRIER b[2];
    UINT nb = 0;
    if (!(declared & D3D12_RESOURCE_STATE_COPY_SOURCE))
      b[nb++] = transition(s, declared, D3D12_RESOURCE_STATE_COPY_SOURCE);
    b[nb++] = transition(c.tex, D3D12_RESOURCE_STATE_NON_PIXEL_SHADER_RESOURCE, D3D12_RESOURCE_STATE_COPY_DEST);
    cl->ResourceBarrier(nb, b);
    cl->CopyResource(c.tex, s);
    nb = 0;
    if (!(declared & D3D12_RESOURCE_STATE_COPY_SOURCE))
      b[nb++] = transition(s, D3D12_RESOURCE_STATE_COPY_SOURCE, declared);
    b[nb++] = transition(c.tex, D3D12_RESOURCE_STATE_COPY_DEST, D3D12_RESOURCE_STATE_NON_PIXEL_SHADER_RESOURCE);
    cl->ResourceBarrier(nb, b);
    cl->Release();
    s->Release();
    *copy_state = D3D12_RESOURCE_STATE_NON_PIXEL_SHADER_RESOURCE;
    return c.tex;
  }

  // ---- capture option ----
  ProbeCaptureHost* capture_host() override { return &files_; }

  WgResultCode capture_copy(void* native_cmd, uint32_t id, uint32_t marker, const std::vector<CaptureSource>& sources,
                            uint64_t budget, uint64_t* bytes, std::vector<std::string>* skipped,
                            std::string* why) override {
    std::lock_guard<std::mutex> lock(mu_);
    if (!dev_) { *why = "no D3D12 device"; return WG_E_COMPUTE_FAILED; }
    if (caps_.count(id)) { *why = "capture " + num(id) + " already pending"; return WG_E_INVALID_PARAMETER; }
    struct Src { ID3D12Resource* r; D3D12_RESOURCE_STATES state; size_t piece; };
    std::vector<Src> res;  // one per distinct resource (a resource tagged twice is copied once)
    Capture c;
    uint64_t off = 0;
    for (const CaptureSource& s : sources) {
      auto skip = [&](const std::string& w) { skipped->push_back("type " + num(s.type) + ": " + w); };
      if (s.view.state == 0xffffffffu) { skip("resource state not given"); continue; }
      ID3D12Resource* r = resource(s.view.resource);
      if (!r) { skip("not a D3D12 resource"); continue; }
      const Src* dup = nullptr;
      for (const Src& x : res)
        if (x.r == r) dup = &x;
      if (dup) {
        if (dup->state != (D3D12_RESOURCE_STATES)s.view.state) skip("same resource as another input, other state");
        else { Piece p = c.pieces[dup->piece]; p.type = s.type; c.pieces.push_back(p); }
        r->Release();
        continue;
      }
      D3D12_RESOURCE_DESC d = r->GetDesc();
      if (d.Dimension != D3D12_RESOURCE_DIMENSION_TEXTURE2D || d.SampleDesc.Count != 1) {
        skip("not a single-sample 2D texture");
        r->Release();
        continue;
      }
      Piece p;
      p.type = s.type;
      p.format = (uint32_t)d.Format;
      p.width = (uint32_t)d.Width;
      p.height = d.Height;
      off = (off + 511) & ~511ull;  // D3D12_TEXTURE_DATA_PLACEMENT_ALIGNMENT
      UINT64 size = 0;
      dev_->GetCopyableFootprints(&d, 0, 1, off, &p.fp, &p.rows, &p.row_bytes, &size);
      if (size == 0 || size == ~0ull || p.row_bytes == 0) {
        skip("no copyable footprint for format " + num(p.format));
        r->Release();
        continue;
      }
      off += size;
      res.push_back(Src{r, (D3D12_RESOURCE_STATES)s.view.state, c.pieces.size()});
      c.pieces.push_back(p);
    }
    auto drop_res = [&]() { for (Src& x : res) x.r->Release(); };
    if (res.empty()) { *why = "no input could be copied"; return WG_E_INVALID_PARAMETER; }
    c.marker_off = (off + 255) & ~255ull;
    c.total = c.marker_off + 256;
    if (c.total > budget) {
      drop_res();
      *why = "size cap: " + num(c.total) + " bytes needed, " + num(budget) + " left";
      return WG_E_INVALID_PARAMETER;
    }
    ID3D12GraphicsCommandList* cl = command_list(native_cmd, why);
    if (!cl) { drop_res(); return WG_E_COMPUTE_FAILED; }
    D3D12_RESOURCE_DESC bd = {};
    bd.Dimension = D3D12_RESOURCE_DIMENSION_BUFFER;
    bd.Width = c.total;
    bd.Height = 1;
    bd.DepthOrArraySize = 1;
    bd.MipLevels = 1;
    bd.SampleDesc.Count = 1;
    bd.Layout = D3D12_TEXTURE_LAYOUT_ROW_MAJOR;
    D3D12_HEAP_PROPERTIES hp = {};
    hp.Type = D3D12_HEAP_TYPE_READBACK;
    if (FAILED(dev_->CreateCommittedResource(&hp, D3D12_HEAP_FLAG_NONE, &bd, D3D12_RESOURCE_STATE_COPY_DEST, nullptr,
                                             __uuidof(ID3D12Resource), reinterpret_cast<void**>(&c.rb)))) {
      cl->Release();
      drop_res();
      *why = "readback buffer of " + num(c.total) + " bytes not created";
      return WG_E_COMPUTE_FAILED;
    }
    {  // the marker slot starts at 0 (markers are never 0)
      D3D12_RANGE none = {0, 0};
      void* m = nullptr;
      if (SUCCEEDED(c.rb->Map(0, &none, &m)) && m) {
        memset(static_cast<uint8_t*>(m) + c.marker_off, 0, 16);
        D3D12_RANGE w = {(SIZE_T)c.marker_off, (SIZE_T)c.marker_off + 16};
        c.rb->Unmap(0, &w);
      }
    }
    // declared state -> copy source (unless the declared state already includes it), copies, and back (61.4 step 7)
    std::vector<D3D12_RESOURCE_BARRIER> to, back;
    for (const Src& x : res)
      if (!(x.state & D3D12_RESOURCE_STATE_COPY_SOURCE)) {
        to.push_back(transition(x.r, x.state, D3D12_RESOURCE_STATE_COPY_SOURCE));
        back.push_back(transition(x.r, D3D12_RESOURCE_STATE_COPY_SOURCE, x.state));
      }
    if (!to.empty()) cl->ResourceBarrier((UINT)to.size(), to.data());
    for (const Src& x : res) {
      const Piece& p = c.pieces[x.piece];
      D3D12_TEXTURE_COPY_LOCATION dst = {}, srcl = {};
      dst.pResource = c.rb;
      dst.Type = D3D12_TEXTURE_COPY_TYPE_PLACED_FOOTPRINT;
      dst.PlacedFootprint = p.fp;
      srcl.pResource = x.r;
      srcl.Type = D3D12_TEXTURE_COPY_TYPE_SUBRESOURCE_INDEX;
      srcl.SubresourceIndex = 0;
      cl->CopyTextureRegion(&dst, 0, 0, 0, &srcl, nullptr);
    }
    if (!back.empty()) cl->ResourceBarrier((UINT)back.size(), back.data());
    // completion marker: written once every preceding command of the list has completed
    ID3D12GraphicsCommandList2* l2 = nullptr;
    if (SUCCEEDED(cl->QueryInterface(__uuidof(ID3D12GraphicsCommandList2), reinterpret_cast<void**>(&l2)))) {
      D3D12_WRITEBUFFERIMMEDIATE_PARAMETER wp = {c.rb->GetGPUVirtualAddress() + c.marker_off, marker};
      D3D12_WRITEBUFFERIMMEDIATE_MODE mode = D3D12_WRITEBUFFERIMMEDIATE_MODE_MARKER_OUT;
      l2->WriteBufferImmediate(1, &wp, &mode);
      l2->Release();
    } else {  // older runtime: a copy of the marker after the transitions back
      bd.Width = 256;
      hp.Type = D3D12_HEAP_TYPE_UPLOAD;
      if (SUCCEEDED(dev_->CreateCommittedResource(&hp, D3D12_HEAP_FLAG_NONE, &bd, D3D12_RESOURCE_STATE_GENERIC_READ,
                                                  nullptr, __uuidof(ID3D12Resource), reinterpret_cast<void**>(&c.up)))) {
        void* m = nullptr;
        D3D12_RANGE none = {0, 0};
        if (SUCCEEDED(c.up->Map(0, &none, &m)) && m) {
          memcpy(m, &marker, 4);
          c.up->Unmap(0, nullptr);
        }
        cl->CopyBufferRegion(c.rb, c.marker_off, c.up, 0, 4);
      }
    }
    cl->Release();
    drop_res();
    *bytes = c.total;
    caps_[id] = c;
    return WG_OK;
  }

  int capture_read(uint32_t id, uint32_t marker, std::vector<CaptureImage>* out) override {
    std::lock_guard<std::mutex> lock(mu_);
    auto it = caps_.find(id);
    if (it == caps_.end()) return -1;
    Capture& c = it->second;
    uint32_t m = 0;
    {
      D3D12_RANGE r = {(SIZE_T)c.marker_off, (SIZE_T)c.marker_off + 4};
      void* p = nullptr;
      if (FAILED(c.rb->Map(0, &r, &p)) || !p) return 0;
      memcpy(&m, static_cast<const uint8_t*>(p) + c.marker_off, 4);
      D3D12_RANGE none = {0, 0};
      c.rb->Unmap(0, &none);
    }
    if (m != marker) return 0;
    D3D12_RANGE all = {0, (SIZE_T)c.total};
    void* p = nullptr;
    if (FAILED(c.rb->Map(0, &all, &p)) || !p) return 0;
    const uint8_t* base = static_cast<const uint8_t*>(p);
    for (const Piece& pc : c.pieces) {
      CaptureImage im;
      im.type = pc.type;
      im.format = pc.format;
      im.width = pc.width;
      im.height = pc.height;
      im.row_pitch = (uint32_t)pc.row_bytes;
      im.data.resize((size_t)pc.rows * (size_t)pc.row_bytes);
      for (UINT y = 0; y < pc.rows; ++y)
        memcpy(im.data.data() + (size_t)y * pc.row_bytes,
               base + pc.fp.Offset + (uint64_t)y * pc.fp.Footprint.RowPitch, (size_t)pc.row_bytes);
      out->push_back(std::move(im));
    }
    D3D12_RANGE none = {0, 0};
    c.rb->Unmap(0, &none);
    release(c.rb);
    release(c.up);
    caps_.erase(it);
    return 1;
  }

  void capture_abandon(uint32_t id) override {
    std::lock_guard<std::mutex> lock(mu_);
    auto it = caps_.find(id);
    if (it == caps_.end()) return;
    if (it->second.rb) retired_.push_back(it->second.rb);  // the GPU may still write it: kept until the device changes
    if (it->second.up) retired_.push_back(it->second.up);
    caps_.erase(it);
  }

 private:
  struct Copy { ID3D12Resource* tex = nullptr; };
  struct Piece {  // one input in a capture's readback buffer
    uint32_t type = 0, format = 0, width = 0, height = 0;
    UINT rows = 0;
    UINT64 row_bytes = 0;
    D3D12_PLACED_SUBRESOURCE_FOOTPRINT fp = {};
  };
  struct Capture {
    ID3D12Resource* rb = nullptr;  // readback buffer: the inputs, then the marker slot
    ID3D12Resource* up = nullptr;  // marker source (only without ID3D12GraphicsCommandList2)
    uint64_t marker_off = 0, total = 0;
    std::vector<Piece> pieces;
  };

  void reset() {
    for (auto& kv : copies_) release(kv.second.tex);
    copies_.clear();
    for (ID3D12Resource*& r : retired_) release(r);
    retired_.clear();
    for (auto& kv : caps_) {
      release(kv.second.rb);
      release(kv.second.up);
    }
    caps_.clear();
    release(readback_);
    release(patch_buf_);
    release(heap_);
    release(pso_up_);
    release(pso_patch_);
    release(rs_);
    release(dev_);
    init_done_ = false;
    init_ok_ = false;
  }

  ID3D12Resource* resource(void* p) {
    ID3D12Resource* r = nullptr;
    if (!p || FAILED(static_cast<IUnknown*>(p)->QueryInterface(__uuidof(ID3D12Resource),
                                                               reinterpret_cast<void**>(&r))))
      return nullptr;
    return r;
  }

  ID3D12GraphicsCommandList* command_list(void* native_cmd, std::string* why) {
    ID3D12GraphicsCommandList* cl = nullptr;
    if (!native_cmd || FAILED(static_cast<IUnknown*>(native_cmd)->QueryInterface(
                           __uuidof(ID3D12GraphicsCommandList), reinterpret_cast<void**>(&cl)))) {
      *why = "the command list is not a D3D12 graphics command list";
      return nullptr;
    }
    D3D12_COMMAND_LIST_TYPE t = cl->GetType();
    if (t != D3D12_COMMAND_LIST_TYPE_DIRECT && t != D3D12_COMMAND_LIST_TYPE_COMPUTE) {
      cl->Release();
      *why = "command list type " + num((uint32_t)t) + " cannot dispatch";
      return nullptr;
    }
    return cl;
  }

  bool ensure(std::string* why) {
    if (!dev_) { *why = "no D3D12 device"; return false; }
    if (init_done_) {
      if (!init_ok_) *why = init_why_;
      return init_ok_;
    }
    init_done_ = true;
#if WG_PROBE_HAS_SHADERS
    HRESULT hr = dev_->CreateRootSignature(0, kProbeUpscaleCs, sizeof kProbeUpscaleCs, __uuidof(ID3D12RootSignature),
                                           reinterpret_cast<void**>(&rs_));
    if (FAILED(hr)) { init_why_ = "root signature not created"; *why = init_why_; return false; }
    D3D12_COMPUTE_PIPELINE_STATE_DESC pd = {};
    pd.pRootSignature = rs_;
    pd.CS.pShaderBytecode = kProbeUpscaleCs;
    pd.CS.BytecodeLength = sizeof kProbeUpscaleCs;
    if (FAILED(dev_->CreateComputePipelineState(&pd, __uuidof(ID3D12PipelineState),
                                                reinterpret_cast<void**>(&pso_up_)))) {
      init_why_ = "upscale pipeline not created";
      *why = init_why_;
      return false;
    }
    pd.CS.pShaderBytecode = kProbePatchCs;
    pd.CS.BytecodeLength = sizeof kProbePatchCs;
    if (FAILED(dev_->CreateComputePipelineState(&pd, __uuidof(ID3D12PipelineState),
                                                reinterpret_cast<void**>(&pso_patch_)))) {
      init_why_ = "patch pipeline not created";
      *why = init_why_;
      return false;
    }
#else
    init_why_ = "built without shaders";
    *why = init_why_;
    return false;
#endif
    D3D12_DESCRIPTOR_HEAP_DESC hd = {};
    hd.Type = D3D12_DESCRIPTOR_HEAP_TYPE_CBV_SRV_UAV;
    hd.NumDescriptors = kHeapSize;
    hd.Flags = D3D12_DESCRIPTOR_HEAP_FLAG_SHADER_VISIBLE;
    if (FAILED(dev_->CreateDescriptorHeap(&hd, __uuidof(ID3D12DescriptorHeap), reinterpret_cast<void**>(&heap_)))) {
      init_why_ = "descriptor heap not created";
      *why = init_why_;
      return false;
    }
    inc_ = dev_->GetDescriptorHandleIncrementSize(D3D12_DESCRIPTOR_HEAP_TYPE_CBV_SRV_UAV);
    D3D12_RESOURCE_DESC bd = {};
    bd.Dimension = D3D12_RESOURCE_DIMENSION_BUFFER;
    bd.Width = kPatchSlots * kSlotBytes;
    bd.Height = 1;
    bd.DepthOrArraySize = 1;
    bd.MipLevels = 1;
    bd.SampleDesc.Count = 1;
    bd.Layout = D3D12_TEXTURE_LAYOUT_ROW_MAJOR;
    bd.Flags = D3D12_RESOURCE_FLAG_ALLOW_UNORDERED_ACCESS;
    D3D12_HEAP_PROPERTIES hp = {};
    hp.Type = D3D12_HEAP_TYPE_DEFAULT;
    if (FAILED(dev_->CreateCommittedResource(&hp, D3D12_HEAP_FLAG_NONE, &bd, D3D12_RESOURCE_STATE_COMMON, nullptr,
                                             __uuidof(ID3D12Resource), reinterpret_cast<void**>(&patch_buf_)))) {
      init_why_ = "patch buffer not created";
      *why = init_why_;
      return false;
    }
    bd.Flags = D3D12_RESOURCE_FLAG_NONE;
    hp.Type = D3D12_HEAP_TYPE_READBACK;
    if (FAILED(dev_->CreateCommittedResource(&hp, D3D12_HEAP_FLAG_NONE, &bd, D3D12_RESOURCE_STATE_COPY_DEST, nullptr,
                                             __uuidof(ID3D12Resource), reinterpret_cast<void**>(&readback_)))) {
      init_why_ = "readback buffer not created";
      *why = init_why_;
      return false;
    }
    init_ok_ = true;
    return true;
  }

  bool supports(uint32_t format, UINT support1, UINT support2) {
    D3D12_FEATURE_DATA_FORMAT_SUPPORT fs = {};
    fs.Format = (DXGI_FORMAT)format;
    if (FAILED(dev_->CheckFeatureSupport(D3D12_FEATURE_FORMAT_SUPPORT, &fs, sizeof fs))) return false;
    return (fs.Support1 & support1) == support1 && (fs.Support2 & support2) == support2;
  }

  // The next pair of descriptors (CPU handle for writing, GPU handle for binding).
  void next_pair(D3D12_CPU_DESCRIPTOR_HANDLE* cpu, D3D12_GPU_DESCRIPTOR_HANDLE* gpu) {
    UINT i = next_;
    next_ = (next_ + 2) % kHeapSize;
    *cpu = heap_->GetCPUDescriptorHandleForHeapStart();
    cpu->ptr += (SIZE_T)i * inc_;
    *gpu = heap_->GetGPUDescriptorHandleForHeapStart();
    gpu->ptr += (UINT64)i * inc_;
  }

  // Shader-resource view of `v` (texture 2D, mip 0). Returns 0 or a result code with `why`.
  WgResultCode read_view(const ProbeView& v, ID3D12Resource* r, D3D12_CPU_DESCRIPTOR_HANDLE at, bool* decode,
                         std::string* why) {
    D3D12_RESOURCE_DESC d = r->GetDesc();
    if (d.Dimension != D3D12_RESOURCE_DIMENSION_TEXTURE2D || d.SampleDesc.Count != 1 || d.DepthOrArraySize != 1) {
      *why = "input is not a single-sample, single-layer 2D texture";
      return WG_E_INVALID_PARAMETER;
    }
    uint32_t f = probe_read_view_format((uint32_t)d.Format, v.format, decode);
    if (!f || !supports(f, D3D12_FORMAT_SUPPORT1_SHADER_LOAD, 0)) {
      *why = "input format " + num(v.format) + " / resource format " + num((uint32_t)d.Format) + " cannot be read";
      return WG_E_INVALID_PARAMETER;
    }
    if (v.x + v.w > d.Width || v.y + v.h > d.Height) {
      *why = "input rectangle outside the resource";
      return WG_E_INVALID_PARAMETER;
    }
    D3D12_SHADER_RESOURCE_VIEW_DESC sd = {};
    sd.Format = (DXGI_FORMAT)f;
    sd.ViewDimension = D3D12_SRV_DIMENSION_TEXTURE2D;
    sd.Shader4ComponentMapping = D3D12_DEFAULT_SHADER_4_COMPONENT_MAPPING;
    sd.Texture2D.MipLevels = 1;
    dev_->CreateShaderResourceView(r, &sd, at);
    return WG_OK;
  }

  WgResultCode record_upscale(ID3D12GraphicsCommandList* cl, const ProbeView& src, const ProbeView& dst,
                              std::string* why) {
    if (src.state == 0xffffffffu || dst.state == 0xffffffffu) {
      *why = "resource state not given";
      return WG_E_MISSING_RESOURCE_STATE;  // 60.6.3: mandatory on D3D12
    }
    if (src.resource == dst.resource) {
      *why = "colour input and output are one resource";
      return WG_E_INVALID_PARAMETER;
    }
    ID3D12Resource* s = resource(src.resource);
    ID3D12Resource* o = resource(dst.resource);
    WgResultCode rc = WG_OK;
    if (!s || !o) {
      *why = "not a D3D12 resource";
      rc = WG_E_INVALID_PARAMETER;
    }
    D3D12_CPU_DESCRIPTOR_HANDLE cpu;
    D3D12_GPU_DESCRIPTOR_HANDLE gpu;
    bool decode = false, encode = false;
    if (rc == WG_OK) {
      next_pair(&cpu, &gpu);
      rc = read_view(src, s, cpu, &decode, why);
    }
    if (rc == WG_OK) {
      D3D12_RESOURCE_DESC d = o->GetDesc();
      uint32_t f = probe_write_view_format((uint32_t)d.Format, dst.format, &encode);
      if (d.Dimension != D3D12_RESOURCE_DIMENSION_TEXTURE2D || d.SampleDesc.Count != 1 || d.DepthOrArraySize != 1) {
        *why = "output is not a single-sample, single-layer 2D texture";
        rc = WG_E_INVALID_PARAMETER;
      } else if (!(d.Flags & D3D12_RESOURCE_FLAG_ALLOW_UNORDERED_ACCESS)) {
        *why = "output resource does not allow unordered access";
        rc = WG_E_INVALID_PARAMETER;
      } else if (!f || !supports(f, D3D12_FORMAT_SUPPORT1_TYPED_UNORDERED_ACCESS_VIEW,
                                 D3D12_FORMAT_SUPPORT2_UAV_TYPED_STORE)) {
        *why = "output format " + num(dst.format) + " / resource format " + num((uint32_t)d.Format) +
               " has no typed unordered-access store";
        rc = WG_E_INVALID_PARAMETER;
      } else if (dst.x + dst.w > d.Width || dst.y + dst.h > d.Height) {
        *why = "output rectangle outside the resource";
        rc = WG_E_INVALID_PARAMETER;
      } else {
        D3D12_UNORDERED_ACCESS_VIEW_DESC ud = {};
        ud.Format = (DXGI_FORMAT)f;
        ud.ViewDimension = D3D12_UAV_DIMENSION_TEXTURE2D;
        D3D12_CPU_DESCRIPTOR_HANDLE c1 = cpu;
        c1.ptr += inc_;
        dev_->CreateUnorderedAccessView(o, nullptr, &ud, c1);
      }
    }
    if (rc == WG_OK) {
      const D3D12_RESOURCE_STATES ss = (D3D12_RESOURCE_STATES)src.state, ds = (D3D12_RESOURCE_STATES)dst.state;
      const bool tsrc = !(ss & D3D12_RESOURCE_STATE_NON_PIXEL_SHADER_RESOURCE);
      const bool tdst = ds != D3D12_RESOURCE_STATE_UNORDERED_ACCESS;
      D3D12_RESOURCE_BARRIER b[2];
      UINT nb = 0;
      if (tsrc) b[nb++] = transition(s, ss, D3D12_RESOURCE_STATE_NON_PIXEL_SHADER_RESOURCE);
      if (tdst) b[nb++] = transition(o, ds, D3D12_RESOURCE_STATE_UNORDERED_ACCESS);
      if (nb) cl->ResourceBarrier(nb, b);
      ID3D12DescriptorHeap* heaps[1] = {heap_};
      cl->SetDescriptorHeaps(1, heaps);
      cl->SetComputeRootSignature(rs_);
      cl->SetPipelineState(pso_up_);
      const UINT k[12] = {src.x, src.y, src.w, src.h, dst.x, dst.y, dst.w, dst.h,
                          (decode ? 1u : 0u) | (encode ? 2u : 0u), 0, 0, 0};
      cl->SetComputeRoot32BitConstants(0, 12, k, 0);
      cl->SetComputeRootDescriptorTable(1, gpu);
      D3D12_GPU_DESCRIPTOR_HANDLE g1 = gpu;
      g1.ptr += inc_;
      cl->SetComputeRootDescriptorTable(2, g1);
      cl->Dispatch((dst.w + 7) / 8, (dst.h + 7) / 8, 1);
      nb = 0;
      if (tsrc) b[nb++] = transition(s, D3D12_RESOURCE_STATE_NON_PIXEL_SHADER_RESOURCE, ss);
      if (tdst) {
        b[nb++] = transition(o, D3D12_RESOURCE_STATE_UNORDERED_ACCESS, ds);
      } else {
        D3D12_RESOURCE_BARRIER ub = {};
        ub.Type = D3D12_RESOURCE_BARRIER_TYPE_UAV;
        ub.UAV.pResource = o;
        b[nb++] = ub;
      }
      cl->ResourceBarrier(nb, b);
    }
    if (s) s->Release();
    if (o) o->Release();
    return rc;
  }

  WgResultCode record_patch(ID3D12GraphicsCommandList* cl, const ProbeView& src, uint32_t px, uint32_t py,
                            uint32_t slot, uint32_t marker, std::string* why) {
    if (src.state == 0xffffffffu) {
      *why = "resource state not given";
      return WG_E_MISSING_RESOURCE_STATE;
    }
    ID3D12Resource* s = resource(src.resource);
    if (!s) {
      *why = "not a D3D12 resource";
      return WG_E_INVALID_PARAMETER;
    }
    D3D12_CPU_DESCRIPTOR_HANDLE cpu;
    D3D12_GPU_DESCRIPTOR_HANDLE gpu;
    next_pair(&cpu, &gpu);
    bool decode = false;
    WgResultCode rc = read_view(src, s, cpu, &decode, why);
    if (rc == WG_OK) {
      D3D12_UNORDERED_ACCESS_VIEW_DESC ud = {};
      ud.Format = DXGI_FORMAT_R32_TYPELESS;
      ud.ViewDimension = D3D12_UAV_DIMENSION_BUFFER;
      ud.Buffer.NumElements = kPatchSlots * kSlotBytes / 4;
      ud.Buffer.Flags = D3D12_BUFFER_UAV_FLAG_RAW;
      D3D12_CPU_DESCRIPTOR_HANDLE c1 = cpu;
      c1.ptr += inc_;
      dev_->CreateUnorderedAccessView(patch_buf_, nullptr, &ud, c1);
      const D3D12_RESOURCE_STATES ss = (D3D12_RESOURCE_STATES)src.state;
      const bool tsrc = !(ss & D3D12_RESOURCE_STATE_NON_PIXEL_SHADER_RESOURCE);
      D3D12_RESOURCE_BARRIER b[2];
      UINT nb = 0;
      if (tsrc) b[nb++] = transition(s, ss, D3D12_RESOURCE_STATE_NON_PIXEL_SHADER_RESOURCE);
      b[nb++] = transition(patch_buf_, D3D12_RESOURCE_STATE_COMMON, D3D12_RESOURCE_STATE_UNORDERED_ACCESS);
      cl->ResourceBarrier(nb, b);
      ID3D12DescriptorHeap* heaps[1] = {heap_};
      cl->SetDescriptorHeaps(1, heaps);
      cl->SetComputeRootSignature(rs_);
      cl->SetPipelineState(pso_patch_);
      const UINT k[12] = {src.x, src.y, src.w, src.h, px, py, 16, 16, decode ? 1u : 0u, slot, marker, 0};
      cl->SetComputeRoot32BitConstants(0, 12, k, 0);
      cl->SetComputeRootDescriptorTable(1, gpu);
      D3D12_GPU_DESCRIPTOR_HANDLE g1 = gpu;
      g1.ptr += inc_;
      cl->SetComputeRootDescriptorTable(2, g1);
      cl->Dispatch(1, 1, 1);
      nb = 0;
      if (tsrc) b[nb++] = transition(s, D3D12_RESOURCE_STATE_NON_PIXEL_SHADER_RESOURCE, ss);
      b[nb++] = transition(patch_buf_, D3D12_RESOURCE_STATE_UNORDERED_ACCESS, D3D12_RESOURCE_STATE_COPY_SOURCE);
      cl->ResourceBarrier(nb, b);
      cl->CopyBufferRegion(readback_, slot * kSlotBytes, patch_buf_, slot * kSlotBytes, kSlotBytes);
      D3D12_RESOURCE_BARRIER back = transition(patch_buf_, D3D12_RESOURCE_STATE_COPY_SOURCE,
                                               D3D12_RESOURCE_STATE_COMMON);
      cl->ResourceBarrier(1, &back);
    }
    s->Release();
    return rc;
  }

  std::mutex mu_;
  ID3D12Device* dev_ = nullptr;
  ID3D12RootSignature* rs_ = nullptr;
  ID3D12PipelineState* pso_up_ = nullptr;
  ID3D12PipelineState* pso_patch_ = nullptr;
  ID3D12DescriptorHeap* heap_ = nullptr;
  ID3D12Resource* patch_buf_ = nullptr;
  ID3D12Resource* readback_ = nullptr;
  UINT inc_ = 0;
  UINT next_ = 0;
  bool init_done_ = false, init_ok_ = false;
  std::string init_why_;
  std::map<uint32_t, Copy> copies_;
  std::vector<ID3D12Resource*> retired_;
  std::map<uint32_t, Capture> caps_;
  FileCaptureHost files_;
};

