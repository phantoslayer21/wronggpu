uint32_t probe_read_view_format(uint32_t res, uint32_t tag, bool* decode) {
  *decode = false;
  const uint32_t base = tag ? tag : res;
  if (format_class(base, false) == WG_FMT_UNSUPPORTED && !is_typeless(base)) return 0;
  uint32_t view;
  if (!is_typeless(res)) {
    if (is_depth(res) || format_class(res, false) == WG_FMT_UNSUPPORTED) return 0;  // typed: the view is the resource's
    view = res;
  } else {
    const Family* m = family_of(res);
    view = typed_member(m, base) ? base : (m->flt ? m->flt : m->unorm ? m->unorm : m->snorm);
  }
  *decode = format_class(base, false) == WG_FMT_SRGB && format_class(view, false) != WG_FMT_SRGB;
  return view;
}

uint32_t probe_write_view_format(uint32_t res, uint32_t tag, bool* encode) {
  *encode = false;
  const uint32_t base = tag ? tag : res;
  if (format_class(base, false) == WG_FMT_UNSUPPORTED && !is_typeless(base)) return 0;
  uint32_t view;
  if (!is_typeless(res)) {
    if (is_depth(res) || format_class(res, false) == WG_FMT_UNSUPPORTED) return 0;
    if (format_class(res, false) == WG_FMT_SRGB) return 0;  // no unordered access in an sRGB format
    view = res;
  } else {
    const Family* m = family_of(res);
    if (format_class(base, false) == WG_FMT_SRGB) view = m->unorm;
    else view = typed_member(m, base) ? base : (m->flt ? m->flt : m->unorm ? m->unorm : m->snorm);
    if (!view) return 0;
  }
  *encode = format_class(base, false) == WG_FMT_SRGB;
  return view;
}

