"""Generate a fake 'original' interposer library for the proxy tests from a binding table.

    python gen_fake_original.py <binding.json> <out_dir> [<file name>]

Writes fake_original.cpp and fake_original.def: a test stand-in of our own that exports every name of the
table's export list (annex A9.3) at its ordinal. Every export records its index and arguments in a state block
(read by the test through the extra export wgtest_fo_state); the role exports have the role signatures the
proxy uses (60.6 declarations, A10 types), every other export one generic signature. Frame tokens have the A10.1
layout (table pointer, header with the table's frame-token GUID at +16, version 1 at +32); the index comes from the
table's first function. <native-interface> returns the native object registered through wgtest_fo_wrap, else the
wrapped pointer + 1. Nothing is taken from a real library.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "tools"))
import gen_forwarding as gf  # noqa: E402

ROLE_IMPL = {
    "init": "uint32_t {n}(const void* p, uint64_t v) {{ if (g_opti_init) g_opti_init(); rec({i}, \"init\", 0); S.u64 = v; S.ptr = p; return 0; }}",
    "shutdown": "uint32_t {n}(void) {{ rec({i}, \"shutdown\", 0); return 0; }}",
    "is-supported": "uint32_t {n}(uint32_t f, const void* a) {{ rec({i}, \"is-supported\", f); S.ptr = a; return 100u + f % 50u; }}",
    "is-loaded": "uint32_t {n}(uint32_t f, bool* l) {{ rec({i}, \"is-loaded\", f); S.ptr = l; return 100u + f % 50u; }}",
    "set-loaded": "uint32_t {n}(uint32_t f, bool l) {{ rec({i}, \"set-loaded\", f); S.u64 = l; return 100u + f % 50u; }}",
    "requirements": "uint32_t {n}(uint32_t f, void* r) {{ rec({i}, \"requirements\", f); S.ptr = r; return 100u + f % 50u; }}",
    "version": "uint32_t {n}(uint32_t f, void* r) {{ rec({i}, \"version\", f); S.ptr = r; return 100u + f % 50u; }}",
    "get-function": "uint32_t {n}(uint32_t f, const char* s, void** o) {{ rec({i}, \"get-function\", f); S.ptr = s; *o = (void*)&fo_dummy; return 100u + f % 50u; }}",
    "allocate": "uint32_t {n}(void* c, uint32_t f, const void* v) {{ rec({i}, \"allocate\", f); S.ptr = v; S.cmd = c; return 100u + f % 50u; }}",
    "free": "uint32_t {n}(uint32_t f, const void* v) {{ rec({i}, \"free\", f); S.ptr = v; return 100u + f % 50u; }}",
    "set-device": "uint32_t {n}(void* d) {{ rec({i}, \"set-device\", 0); S.ptr = d; return 0; }}",
    "tag": "uint32_t {n}(const void* v, const void* t, uint32_t c, void* l) {{ rec({i}, \"tag\", 0); S.ptr = t; S.count = c; S.cmd = l; (void)v; return 0; }}",
    "tag-for-frame": "uint32_t {n}(const void* k, const void* v, const void* t, uint32_t c, void* l) {{ rec({i}, \"tag-for-frame\", 0); S.ptr = t; S.count = c; S.cmd = l; (void)k; (void)v; return 0; }}",
    "constants": "uint32_t {n}(const void* c, const void* k, const void* v) {{ rec({i}, \"constants\", 0); S.ptr = c; (void)k; (void)v; return 0; }}",
    "new-frame-token": "uint32_t {n}(void** out, const uint32_t* idx) {{ rec({i}, \"new-frame-token\", 0); FoToken* t = &g_tokens[g_next++ % 64]; t->vt = kVt; t->next = 0; memcpy(t->guid, kTokenGuid, 16); t->ver = 1; t->index = idx ? *idx : 1000u + g_next; *out = t; return 0; }}",
    "evaluate": "uint32_t {n}(uint32_t f, const void* k, const void* const* in, uint32_t c, void* l) {{ rec({i}, \"evaluate\", f); S.ptr = in; S.count = c; S.cmd = l; (void)k; return 100u + f % 50u; }}",
    "native-interface": "uint32_t {n}(void* w, void** o) {{ rec({i}, \"native-interface\", 0); for (int k = 0; k < g_nwrap; ++k) if (g_wrap[k][0] == w) {{ *o = g_wrap[k][1]; return 0; }} *o = (char*)w + 1; return 0; }}",
}


def main(argv):
    b, _ = gf.load(argv[1])
    n = gf.validate(b)
    os.makedirs(argv[2], exist_ok=True)
    src = ["// generated by clean/rr_f/proxy/tests/gen_fake_original.py - test stand-in of our own, no real library",
           "#include <stdint.h>", "#include <string.h>", "extern \"C\" {",
           "struct FoState { int calls; int last_index; const char* last_role; uint32_t feature; uint64_t a1, a3, a5, a6;",
           "  double a2, a4, a7; uint64_t u64; const void* ptr; void* cmd; uint32_t count; };",
           "static FoState S;",
           "__declspec(dllexport) FoState* wgtest_fo_state(void) { return &S; }",
           "static void rec(int i, const char* r, uint32_t f) { S.calls++; S.last_index = i; S.last_role = r; S.feature = f; }",
           "static uint32_t fo_dummy(void) { return 0; }",
           "struct FoToken { const void* vt; void* next; unsigned char guid[16]; uint64_t ver; uint32_t index; };",
           "static uint32_t fo_token_index(const FoToken* t) { return t->index; }",
           "static const void* const kVt[1] = {(const void*)&fo_token_index};",
           "static FoToken g_tokens[64]; static uint32_t g_next = 0;",
           "static const unsigned char kTokenGuid[16] = {" + ", ".join(str(x) for x in n["guids"].get("frame_token", [0] * 16)) + "};",
           "static void* g_wrap[16][2]; static int g_nwrap = 0;",
           "__declspec(dllexport) void wgtest_fo_wrap(void* wrapped, void* native) { if (g_nwrap < 16) { g_wrap[g_nwrap][0] = wrapped; g_wrap[g_nwrap][1] = native; ++g_nwrap; } }",
           "// Models OptiScaler's inline patch on the interface's init export: a hook the init body calls first,",
           "// so a caller that forwards through the export address (GetProcAddress) keeps the patch in the chain.",
           "typedef void (*FoOptiHook)(void); static FoOptiHook g_opti_init = 0;",
           "__declspec(dllexport) void wgtest_fo_set_opti_init(FoOptiHook h) { g_opti_init = h; }"]
    exports = []
    for i, name in enumerate(n["ordered"]):
        role = n["role_of"].get(name)
        sym = f"fo_{i}"
        if role in ROLE_IMPL:
            src.append(ROLE_IMPL[role].format(n=sym, i=i))
        else:
            src.append(f"uint64_t {sym}(uint64_t a1, double a2, uint64_t a3, double a4, uint64_t a5, "
                       f"uint64_t a6, double a7) {{ rec({i}, \"generic\", 0); S.a1 = a1; S.a2 = a2; S.a3 = a3; "
                       f"S.a4 = a4; S.a5 = a5; S.a6 = a6; S.a7 = a7; return a1 * 31u + {i}u; }}")
        exports.append(f"  {name}={sym} @{n['ordinals'][name]}")
    src.append("}")
    with open(os.path.join(argv[2], "fake_original.cpp"), "wb") as f:
        f.write(("\n".join(src) + "\n").encode())
    # Keep the full file name (with .dll) as the module/import name: the hook test imports this DLL by that exact
    # name through its import table, so it must match the interposer file name byte for byte.
    lib = argv[3] if len(argv) > 3 else n["original_file"]
    with open(os.path.join(argv[2], "fake_original.def"), "wb") as f:
        f.write((f'LIBRARY "{lib}"\nEXPORTS\n' + "\n".join(exports) +
                 "\n  wgtest_fo_state\n  wgtest_fo_wrap\n  wgtest_fo_set_opti_init\n").encode())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
