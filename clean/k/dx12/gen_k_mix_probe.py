"""Writes clean/k/runtime/k_mix_probe.h: the records and exact expected FP16 results of the native D3D12 runtime's
softmax rounding probe (kernels/k_mix_probe.hlsl, run at create; k_mix_cases.py, seed 7, 64 lanes = two workgroups).
WrongGPU's own code. clean/k/tests/test_k_mix_probe_table.py checks the committed header against this output.

    python clean/k/dx12/gen_k_mix_probe.py [out.h]
    python clean/k/dx12/gen_k_mix_probe.py --check     (exit 1 unless the committed header equals this output)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
sys.path.insert(0, ROOT)
from clean.k.dx12 import k_mix_cases  # noqa: E402

SEED, LANES = 7, 64
DEFAULT_OUT = os.path.join(ROOT, "clean", "k", "runtime", "k_mix_probe.h")


def header():
    rec, want, kinds = k_mix_cases.cases(SEED, LANES)
    dbl = k_mix_cases.double_rounding_bits(rec)
    words = rec.view("<u4").ravel().tolist()
    exp = want.ravel().tolist()
    out = ["// SPDX-License-Identifier: MIT",
           "// Generated by clean/k/dx12/gen_k_mix_probe.py (k_mix_cases.py seed %d, %d lanes); do not edit." % (SEED, LANES),
           "// The native D3D12 runtime's softmax rounding probe (clean/k/dx12/kernels/k_mix_probe.hlsl): per lane 12 FP32",
           "// words (inv, w0 .. w7, 0, 0, 0) and the 8 exact FP16 results RN16(w_j inv). A second rounding through FP32 differs",
           "// from them in %d of the %d results." % (int((dbl != want).sum()), want.size),
           "#pragma once",
           "",
           "#include <cstdint>",
           "",
           "namespace k_mix_probe {",
           "",
           "constexpr int kLanes = %d;" % LANES,
           "constexpr uint32_t kRecords[kLanes * 12] = {"]
    for i in range(0, len(words), 8):
        out.append("    " + ", ".join("0x%08xu" % w for w in words[i:i + 8]) + ",")
    out.append("};")
    out.append("constexpr uint16_t kExpected[kLanes * 8] = {")
    for i in range(0, len(exp), 8):
        out.append("    " + ", ".join("0x%04x" % w for w in exp[i:i + 8]) + ",")
    out += ["};", "", "}  // namespace k_mix_probe", ""]
    return "\n".join(out)


if __name__ == "__main__":
    if sys.argv[1:] == ["--check"]:
        with open(DEFAULT_OUT, encoding="utf-8", newline="") as f:
            same = f.read() == header()
        print(DEFAULT_OUT, "matches the generator" if same else "DIFFERS from the generator")
        sys.exit(0 if same else 1)
    path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_OUT
    with open(path, "w", newline="\n") as f:
        f.write(header())
    print(path)
