"""Writes clean/k/runtime/k_smx_selfcheck.h: the reference hashes of model K's softmax self-check (runtime_k.cpp
"create-time self-check"; KRuntime::smx_select) and the source digest they belong to. Each case runs one softmax stage
kernel at one window offset on the runtime's own synthetic inputs and weights; the header holds the SHA-256 (first 8
bytes) of its outputs on the HIP reference, for every offset any model's window table can give. The native D3D12
device compares both of its forms (mix and __rodd) at its model's offsets with these values at create. kSourceDigest
(smx_selfcheck_digest.py) binds the values to the shader sources, definitions and runtime regions they came from; the
builds refuse a header whose digest differs. WrongGPU's own code.

    python clean/k/dx12/gen_k_smx_selfcheck.py --build <build dir>   (GPU: a runtime library built from this tree with
        clean/runner/build.py --dev-diagnostics, HIP code objects, ROCM_PATH; runs the HIP backend with the developer
        hook k_smx_test=report and writes the header)
    python clean/k/dx12/gen_k_smx_selfcheck.py --bootstrap            (a placeholder header: lets a first developer build
        exist; a native D3D12 create refuses with it)
"""
import argparse
import ctypes
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
sys.path.insert(0, ROOT)
from clean.k.dx12 import smx_selfcheck_digest as D  # noqa: E402

OUT = os.path.join(ROOT, D.HEADER)
TAG = "model K self-check reference:"


def header(entries, source_digest):
    out = ["// SPDX-License-Identifier: MIT",
           "// Generated by clean/k/dx12/gen_k_smx_selfcheck.py; do not edit. The reference hashes (SHA-256 of the outputs,",
           "// first 8 bytes) of model K's softmax self-check cases at every possible window offset (runtime_k.cpp kSmxCases,",
           "// KRuntime::smx_select) on the HIP reference, and the source digest they belong to (smx_selfcheck_digest.py).",
           "#pragma once",
           "",
           "#include <cstdint>",
           "",
           "namespace k_smx_selfcheck {",
           "",
           'constexpr char kSourceDigest[] = "%s";' % source_digest,
           "constexpr int kCount = %d;" % len(entries),
           "constexpr const char* kNames[kCount] = {"]
    out += ['    "%s",' % n for n, _ in entries]
    out += ["};", "constexpr uint64_t kExpected[kCount] = {"]
    out += ["    0x%016xull," % v for _, v in entries]
    out += ["};", "", "}  // namespace k_smx_selfcheck", ""]
    return "\n".join(out)


def reference(build):
    import tempfile

    from clean.k.reference.network import random_network_params
    from clean.k.tests.test_k_runtime_gpu import KRuntimeExt, write_k_model
    mdir = tempfile.mkdtemp(prefix="k_smx_ref_")
    _, map_path = write_k_model(mdir, random_network_params(11))
    rt = KRuntimeExt(build, mdir, map_path, (200, 120), (130, 78), True, False, False, "k_smx_test=report", backend=0)
    rt.lib.wg_rt_notes.argtypes = [ctypes.c_void_p]
    rt.lib.wg_rt_notes.restype = ctypes.c_char_p
    notes = rt.lib.wg_rt_notes(rt.rt).decode().split("\n")
    line = [n for n in notes if n.startswith(TAG)]
    if len(line) != 1:
        raise SystemExit("no reference line in the notes (a --dev-diagnostics build?): %r" % notes)
    entries = [(kv.split("=", 1)[0], int(kv.split("=", 1)[1], 16)) for kv in line[0][len(TAG):].split()]
    if len({n for n, _ in entries}) != len(entries):
        raise SystemExit("duplicate case names in the reference")
    return entries


def main():
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--build")
    g.add_argument("--bootstrap", action="store_true")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args()
    entries = [("bootstrap", 0)] if a.bootstrap else reference(a.build)
    text = header(entries, D.digest())
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(a.out, len(entries), "case(s), source digest", D.digest())


if __name__ == "__main__":
    main()
