"""Writes clean/k/runtime/k_smx_selfcheck.h: the reference hashes of model K's softmax self-check (runtime_k.cpp
"create-time self-check"; KRuntime::smx_select). Each case runs one softmax stage kernel on the runtime's own synthetic
inputs and weights; the header holds the SHA-256 (first 8 bytes) of its outputs on the HIP reference. The native D3D12
device compares both of its forms (mix and __rodd) with these values at create. WrongGPU's own code.

    python clean/k/dx12/gen_k_smx_selfcheck.py --build <build dir>   (GPU: a runtime library built with
        clean/runner/build.py --dev-diagnostics, HIP code objects, ROCM_PATH; runs the HIP backend with the developer
        hook k_smx_test=report and writes the header)
    python clean/k/dx12/gen_k_smx_selfcheck.py --bootstrap            (the case names with zero hashes: lets a first
        developer build exist; a native D3D12 create refuses with it)
"""
import argparse
import ctypes
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
sys.path.insert(0, ROOT)
OUT = os.path.join(ROOT, "clean", "k", "runtime", "k_smx_selfcheck.h")
# KRuntime::smx_case_name for runtime_k.cpp kSmxCases, in order (the runtime checks the names at create)
NAMES = ["k_stage_e2@512x384", "k_stagew2_e3@512x384", "k_stagew4_e4@512x384*8", "k_stagew4_m@512x384",
         "k_stagew4_d4@512x384*8", "k_stagew2_d3@512x384", "k_stage_d2@512x384", "k_stage2_d1@512x384",
         "k_stagew2_e4@1536x1280", "k_stagew2_d4@1536x1280", "k_stagew4_m@1536x1280"]
TAG = "model K self-check reference:"


def header(values):
    out = ["// SPDX-License-Identifier: MIT",
           "// Generated by clean/k/dx12/gen_k_smx_selfcheck.py; do not edit. The reference hashes (SHA-256 of the outputs,",
           "// first 8 bytes) of model K's softmax self-check cases (runtime_k.cpp kSmxCases, KRuntime::smx_select) on the",
           "// HIP reference." + (" BOOTSTRAP: zero hashes (a native D3D12 create refuses)." if not any(values) else ""),
           "#pragma once",
           "",
           "#include <cstdint>",
           "",
           "namespace k_smx_selfcheck {",
           "",
           "constexpr int kCount = %d;" % len(NAMES),
           "constexpr const char* kNames[kCount] = {"]
    out += ['    "%s",' % n for n in NAMES]
    out += ["};", "constexpr uint64_t kExpected[kCount] = {"]
    out += ["    0x%016xull,  // %s" % (v, n) for v, n in zip(values, NAMES)]
    out += ["};", "", "}  // namespace k_smx_selfcheck", ""]
    return "\n".join(out)


def reference(build):
    import tempfile

    from clean.k.reference.network import random_network_params
    from clean.k.tests.test_k_runtime_gpu import KRuntimeExt, write_k_model
    mdir = tempfile.mkdtemp(prefix="k_smx_ref_")
    _, map_path = write_k_model(mdir, random_network_params(11))
    rt = KRuntimeExt(build, mdir, map_path, (200, 120), (130, 78), True, False, False, "k_smx_test=report", backend=0)
    rt.lib.wg_rt_notes.argtypes = [ctypes.c_void_p]
    rt.lib.wg_rt_notes.restype = ctypes.c_char_p
    notes = rt.lib.wg_rt_notes(rt.rt).decode().split("\n")
    line = [n for n in notes if n.startswith(TAG)]
    if len(line) != 1:
        raise SystemExit("no reference line in the notes (a --dev-diagnostics build?): %r" % notes)
    got = dict(kv.split("=", 1) for kv in line[0][len(TAG):].split())
    if list(got) != NAMES:
        raise SystemExit("case names differ from the runtime's: %r" % list(got))
    return [int(got[n], 16) for n in NAMES]


def main():
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--build")
    g.add_argument("--bootstrap", action="store_true")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args()
    values = [0] * len(NAMES) if a.bootstrap else reference(a.build)
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(header(values))
    print(a.out)
    for n, v in zip(NAMES, values):
        print("  %016x  %s" % (v, n))


if __name__ == "__main__":
    main()
