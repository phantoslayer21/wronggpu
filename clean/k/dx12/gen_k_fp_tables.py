"""Generates k_fp_tables.hlsli: the constants of model K's exact FP32 / FP64 helpers (k_fp.h) as bit
patterns for the D3D12 port (k_fp.hlsli). WrongGPU's own code.

k_fp.h builds its tables at compile time (constexpr binary64 series KfExpTab / KfLogTab) and folds constants such as
1.0 / 23.0 or (float)(1.0 / 3.0). HLSL has no constexpr evaluation in binary64 and its float literals are parsed by
DXC, so the port takes every such value as bits computed here with the same IEEE operations in the same order (Python
floats are binary64 with round to nearest even; numpy.float32 rounds binary64 to binary32 to nearest even, as the C
casts do). clean/dx12/build_dx12.py runs it into <out>/dx12/gen (an include folder of the K ports), so the tables are
computed at every build and never stored in the repository:  python clean/k/dx12/gen_k_fp_tables.py <output header>
"""
import os
import struct
import sys

import numpy as np



def f32(v):
    return struct.unpack("<I", np.float32(v).tobytes())[0]


def f64(v):
    b = struct.unpack("<Q", struct.pack("<d", v))[0]
    return b & 0xFFFFFFFF, b >> 32


def kc_exp(x):  # k_fp.h kc_exp, |x| <= 0.4
    t, s = 1.0, 1.0
    for k in range(1, 30):
        t = t * x / k
        s = s + t
    return s


def kc_log(x):  # k_fp.h kc_log, x in [0.5, 2]
    s = (x - 1.0) / (x + 1.0)
    s2 = s * s
    t, r = s, 0.0
    for k in range(40):
        r = r + t / (2 * k + 1)
        t = t * s2
    return 2.0 * r


KC_LN2 = 0.69314718055994530942


def main(out_path):
    exp_h, exp_l = [], []
    for i in range(65):  # KfExpTab: 2^(j/64), j = -32 .. 32
        v = kc_exp((i - 32) / 64.0 * KC_LN2)
        h = float(np.float32(v))
        exp_h.append(f32(h))
        exp_l.append(f32(v - h))
    log_inv, log_h, log_l = [], [], []
    for i in range(97):  # KfLogTab: c_j = 1 + j/128, inv_j = RN32(1/c_j), -log2(inv_j) as hi + lo
        c = 1.0 + (i - 32) / 128.0
        inv = float(np.float32(1.0 / c))
        log_inv.append(f32(inv))
        v = -kc_log(inv) / KC_LN2
        h = float(np.float32(v))
        log_h.append(f32(h))
        log_l.append(f32(v - h))

    def arr(name, vals):
        rows = [", ".join(f"0x{v:08X}u" for v in vals[i:i + 8]) for i in range(0, len(vals), 8)]
        return f"static const uint {name}[{len(vals)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"

    def dconst(name, v):
        lo, hi = f64(v)
        return f"#define {name} asdouble(0x{lo:08X}u, 0x{hi:08X}u)  // {v!r}\n"

    def fconst(name, v):
        return f"#define {name} asfloat(0x{f32(v):08X}u)  // {float(np.float32(v))!r}\n"

    third = 1.0 / 3.0
    third_h = float(np.float32(third))
    inv_ln2 = 1.4426950408889634074
    ln2 = 0.69314718055994530942
    out = ["// Generated by clean/k/dx12/gen_k_fp_tables.py at build time: the constants of k_fp.h as bits. WrongGPU's own code.\n",
           "#pragma once\n\n",
           "// KfExpTab: 2^(j/64), j = -32 .. 32, hi + lo\n", arr("KF_EXP_H", exp_h), arr("KF_EXP_L", exp_l),
           "// KfLogTab: inv_j = RN32(1 / (1 + j/128)), -log2(inv_j) as hi + lo, j = -32 .. 64\n",
           arr("KF_LOG_INV", log_inv), arr("KF_LOG_H", log_h), arr("KF_LOG_L", log_l), "\n",
           "// binary64 constants of kd_log_core / kd_log / kd_log2 / kd_exp2 (k_fp.h; folded there at compile time)\n",
           dconst("KD_LN2", 0.6931471805599453094), dconst("KD_INV_LN2", 1.4426950408889634074),
           dconst("KD_SQRT2", 1.4142135623730951), dconst("KD_INV23", 1.0 / 23.0)]
    out.append("// 1 / (2k + 1), k = 0 .. 10 (kd_log_core's series)\n")
    out.append("static const uint2 KD_INV_ODD[11] = {\n    " + ",\n    ".join(
        "uint2(0x%08Xu, 0x%08Xu)" % f64(1.0 / (2 * k + 1)) for k in range(11)) + "\n};\n")
    out.append("// 1 / k, k = 0 .. 16 (kd_exp2's series; entry 0 unused)\n")
    out.append("static const uint2 KD_INV_K[17] = {\n    uint2(0u, 0u),\n    " + ",\n    ".join(
        "uint2(0x%08Xu, 0x%08Xu)" % f64(1.0 / k) for k in range(1, 17)) + "\n};\n\n")
    out.append("// binary32 constants of kf2_log2 / kf2_exp2 / kf_ln (k_fp.h)\n")
    out += [fconst("KF_THIRD_H", third), fconst("KF_THIRD_L", third - third_h),
            fconst("KF_SIXTH", np.float32(1.0) / np.float32(6.0)), fconst("KF_1_120", np.float32(1.0) / np.float32(120.0)),
            fconst("KF_1_24", np.float32(1.0) / np.float32(24.0)), fconst("KF_1_64", np.float32(1.0) / np.float32(64.0)),
            fconst("KF2_INV_LN2_H", inv_ln2), fconst("KF2_INV_LN2_L", inv_ln2 - float(np.float32(inv_ln2))),
            fconst("KF2_LN2_H", ln2), fconst("KF2_LN2_L", ln2 - float(np.float32(ln2)))]
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    with open(out_path, "w", newline="\n") as f:
        f.write("".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
