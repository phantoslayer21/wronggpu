// Silent mode and entry point
// ------------------------------------------------------------------------------------------------
// Silent mode (/S). Options:
//   /DIR=<folder> or /EXE=<game .exe>   the game (a store folder, the exe folder or the exe)
//   /MODEL=<nvngx_dlss.dll>             a DLSS model file to try first (alias /DLSSDLL=)
//   /EXPERIMENTAL                        confirm installing into a game that is not validated
//   /MOVEMODS                            agree to move other upscaler mods' files aside (kept in the backup)
//   /REMOVEOLD                           agree to remove an older WrongGPU / DLSS 4.5 AMD install first
//   /NOSCAN                              do not look at the store libraries (game list, model search)
//   /FORCE                               do not require the RX 9000-series GPU and HIP runtime (tests, development)
//   /UNINSTALL                           uninstall from the folder (with /OUT=<zip>: collect logs first)
//   /COLLECT [/OUT=<zip>]                collect logs only
//   /OPTISCALER=<.7z | .zip | folder>    OptiScaler mode: the player's OptiScaler takes the game's DLSS / XeSS / FSR
//                                        inputs and hands them to WrongGPU (set up for it; never shipped by WrongGPU)
//   /FSR4                                log which AMD FSR 4 DLL an install would record for the comparison key
//   /LIST                                list the detected games and their checks in the log
//   /HIPCHECK                            run the HIP runtime check alone and log the DLL, device and architecture
//   /LOG=<file>                          log file (default %LOCALAPPDATA%\WrongGPU\setup.log)
// Exit codes: enum ExitCode at the top of this file.
int RunSilent() {
    Ui ui;
    ui.step = [](int, int, const wstring&) {};
    ui.log = [](const wstring& s) { LogLine(g.ctx, s); };
    try {
        LogLine(g.ctx, wstring(kAppName) + L" " + g.ctx.data->version + L" (build " + g.ctx.data->buildId + L", payload " + g.ctx.data->payloadName + L")" + (g.list ? L" - list games" : g.collect && !g.uninstall ? L" - collect logs" : g.uninstall ? L" - silent uninstall" : L" - silent install"));
        if (g.hipCheck) {  // diagnostic: the HIP runtime check alone, whatever the adapter name says
            const HipInfo h = CheckHip(g.ctx);
            LogLine(g.ctx, L"HIP check: " + (h.ok ? L"OK - " + h.device + L" (" + h.arch + L") with " + h.dll : h.text));
            return h.ok ? EXIT_OK : EXIT_REFUSED;
        }
        if (g.fsr4) {  // read-only: the AMD FSR 4 DLL an install would record for the comparison key
            const CompareDll fc = FindCompareDll(g.ctx, ScanLibraries());
            LogLine(g.ctx, fc.path.empty() ? wstring(L"FSR 4 for the comparison key: none found (Home compares with the game's own AMD FSR)")
                                    : L"FSR 4 for the comparison key: " + fc.path + L" (" + fc.version + L", " + fc.game + L")");
            return EXIT_OK;
        }
        if (g.list) {  // read-only: what the wizard would show, with the checks for each game
            for (auto& f : DetectGames(ScanLibraries())) {
                GameTarget t = InspectGame(g.ctx, f.exe, f.name);
                Checks c = RunChecks(g.ctx, t, g.sys, nullptr, g.force);
                LogLine(g.ctx, L"game " + f.name + L" [" + f.source + L"] " + (f.validated ? L"VALIDATED" : L"experimental") + L" -> " + f.exe + L" | install folder " + t.dir);
                for (int i = 0; i < L_COUNT; ++i) LogLine(g.ctx, wstring(c.st[i] == CK_OK ? L"    ok    " : c.st[i] == CK_WARN ? L"    warn  " : c.st[i] == CK_NA ? L"    n/a   " : L"    FAIL  ") + c.text[i]);
            }
            const CompareDll fc = FindCompareDll(g.ctx, ScanLibraries());  // what an install would record (nothing written here)
            LogLine(g.ctx, fc.path.empty() ? wstring(L"FSR 4 for the comparison key: none found (Home compares with the game's own AMD FSR)")
                                    : L"FSR 4 for the comparison key: " + fc.path + L" (" + fc.version + L", " + fc.game + L")");
            return EXIT_OK;
        }
        if (g.collect && !g.uninstall) {
            wstring dir = g.target.dir.empty() ? FullPath(g.input) : g.target.dir;
            Bundle b = CollectLogs(g.ctx, dir, g.outZip.empty() ? DefaultBundlePath(dir) : g.outZip, g.sys);
            for (auto& f : b.files) LogLine(g.ctx, L"  bundled " + f);
            return EXIT_OK;
        }
        if (g.uninstall) {
            const wstring dir = g.target.dir;
            if (dir.empty()) Fail(L"No game folder given. Pass /DIR=<folder with amd_fidelityfx_dx12.dll>.", EXIT_USAGE);
            Record m;
            if (!LoadRecord(RecordPath(dir), m) || m.legacy) Fail(L"No WrongGPU installation record was found in " + dir + L".", EXIT_NOT_INSTALLED);
            if (GameRunning(m.exe)) Fail(BaseName(m.exe) + L" is running. Close it and run the uninstaller again.", EXIT_REFUSED);
            if (!g.outZip.empty()) { CollectLogs(g.ctx, dir, g.outZip, g.sys); LogLine(g.ctx, L"logs collected into " + g.outZip + L" before uninstalling"); }
            for (auto& w : DoRestore(g.ctx, dir, ui, false, false)) LogLine(g.ctx, L"warning: " + w);
            LogLine(g.ctx, L"uninstall complete");
            return EXIT_OK;
        }
        RequireOptiScaler(g.ctx);
        if (g.target.exe.empty()) Fail(L"No game executable found. Pass /EXE=<game .exe> or /DIR=<game folder>.", EXIT_REFUSED);
        LogLine(g.ctx, L"game: " + g.target.exe + L" (" + (g.target.validated ? L"validated" : L"experimental") + L"), install folder " + g.target.dir);
        const std::vector<StoreGame> libraries = g.noScan ? std::vector<StoreGame>{} : ScanLibraries();
        ModelState model = FindModel(g.ctx, &g.target, g.userDll, libraries);
        if (model.ok()) LogLine(g.ctx, L"model source: " + (model.reused ? wstring(L"model data already on this PC") : model.dll + L" (" + model.origin + L")"));
        else LogLine(g.ctx, L"model source: none (" + model.error + L")");
        if (model.ok() && !model.outcome.empty()) LogLine(g.ctx, L"model data: " + model.outcome);
        Checks c = RunChecks(g.ctx, g.target, g.sys, &model, g.force);
        for (int i = 0; i < L_COUNT; ++i) LogLine(g.ctx, wstring(c.st[i] == CK_OK ? L"  ok    " : c.st[i] == CK_WARN ? L"  warn  " : c.st[i] == CK_NA ? L"  n/a   " : L"  FAIL  ") + c.text[i]);
        wstring why;
        if (int code = c.firstFailure(g.force, why)) Fail(why, code);
        if (NeedsConsent() && !g.experimentalOk) Fail(g.target.name + L" is experimental. Pass /EXPERIMENTAL to install anyway.", EXIT_EXPERIMENTAL);
        if (g.target.conflicts.modsFound() && !g.moveMods) {
            wstring list; for (auto& f : g.target.conflicts.modFiles) list += (list.empty() ? L"" : L", ") + f;
            Fail(L"Other upscaler mods were found (" + list + L"). Pass /MOVEMODS to move them aside; they are kept in the backup and restored on uninstall.", EXIT_OTHER_MODS);
        }
        if (g.target.conflicts.oldFound() && !g.removeOld)
            Fail(L"An older WrongGPU (DLSS 4.5 AMD) install was found. Pass /REMOVEOLD to remove it first (its originals are restored byte for byte).", EXIT_OLD_INSTALL);
        if (DWORD e = WriteTest(g.target.dir)) {
            if (e == ERROR_ACCESS_DENIED && !IsElevated()) Fail(L"Administrator permission is required for this folder. Re-run elevated.", EXIT_REFUSED);
        }
        Consent consent; consent.moveMods = g.moveMods; consent.removeOld = g.removeOld;
        for (auto& w : DoInstall(g.ctx, g.target, model, consent, ui, g.sys.hip)) LogLine(g.ctx, L"warning: " + w);
        if (!g.ctx.perGameEntry) AddManagedGame(g.target.dir);  // the installed launcher's entry covers it: on its list
        LogLine(g.ctx, L"install complete");
        return EXIT_OK;
    } catch (const SetupError& e) { LogLine(g.ctx, L"ERROR: " + e.msg); return e.code; }
}

