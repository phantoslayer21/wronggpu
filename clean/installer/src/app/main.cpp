// store scan, anti-cheat lists, install record, backup/restore engine, log collector and wizard come from there.
// Changed for the FSR design (spec 20, 30): WrongGPU replaces the game's amd_fidelityfx_dx12.dll (AMD's DLL is kept
// next to it as amd_fidelityfx_dx12.wronggpu-original.dll), the payload is the FSR front end plus the clean runtime
// and its kernels, and the model data is converted once per PC from the player's own DLSS model file by the clean
// converter (clean/converter, spec 08) into %LOCALAPPDATA%\WrongGPU\model\. See clean/installer/README.md.
//
// One executable, four jobs:
//   * Setup wizard (default): lists the FSR 3.1 games it finds (Steam, Epic, GOG) or takes any game .exe or folder,
//     checks the requirements, prepares the model, backs up every file it will touch, installs the embedded payload
//     and registers one "Apps & features" entry per game.
//   * Uninstaller (run as <game>\wronggpu-setup\uninstall.exe, or /UNINSTALL): restores the backed-up originals.
//   * Log collector (/COLLECT, the "Collect logs" button, or "Modify" in Apps & features).
//   * Silent mode (/S) for scripting and tests (options and exit codes: see RunSilent and README.md).
// It never uses the network and has no telemetry.
//
// The engine (game detection, checks, model data, install record, install, restore, log collector) is the library
// wg_core (src/wg_core, a wg::Context instead of globals); this file is the wizard and the command line on top of it.
// app/main.cpp: the command line, silent mode and the entry point; app/wizard.cpp: the wizard.
