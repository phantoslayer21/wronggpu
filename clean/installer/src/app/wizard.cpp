void RefreshChecks() {
    wchar_t buf[1024]; GetWindowTextW(g.edPath, buf, 1024);
    wstring exe = ResolveGameExe(buf);
    wstring name;
    for (auto& f : g.found) if (IEq(f.exe, exe)) name = f.name;
    g.target = exe.empty() ? GameTarget{} : Inspect(exe, name);
    // A new search when there is no usable model yet and the game (whose folder is searched first) changed.
    // The same when the model on this PC could still gain the output-filter weights from a file in the new game's folder.
    if (!g.target.exe.empty() && g.model.status != ModelState::SEARCHING && (!g.model.ok() || g.model.stale) && !IEq(g.modelFor, g.target.exe)) StartModelSearch();
    if (!g.target.exe.empty() && g.model.status == ModelState::NONE) StartModelSearch();
    g.checks = RunChecks(g.ctx, g.target, g.sys, g.target.exe.empty() ? nullptr : &g.model, g.force);
    wstring checkText;
    for (int i = 0; i < L_COUNT; ++i) {
        const wchar_t* mark = g.checks.st[i] == CK_OK ? L"OK" : g.checks.st[i] == CK_FAIL ? L"FIX" : g.checks.st[i] == CK_WARN ? L"NOTE" : L"--";
        checkText += wstring(mark) + L"  " + g.checks.text[i] + L"\r\n";
    }
    SetWindowTextW(g.edChecks, checkText.c_str());
    wstring status;
    if (g.target.exe.empty()) status = L"";
    else if (g.target.validated) status = L"TESTED GAME  \u00b7  " + g.target.name + L". Settings and other mods can affect compatibility.";
    else status = L"EXPERIMENTAL  \u00b7  " + g.target.name + L". Game detection does not confirm compatibility.";
    SetWindowTextW(g.stStatus, status.c_str());
    wstring hint;
    if (!g.target.antiCheat.empty())
        hint = L"This game uses anti-cheat (" + g.target.antiCheat + L"). Games with anti-cheat are never supported: a modified game file can get your account banned.";
    else if (!g.target.exe.empty() && g.model.status == ModelState::FAILED) {
        hint = g.model.error;
        if (!g.model.rejections.empty()) hint += L" (" + std::to_wstring(g.model.rejections.size()) + L" file(s) checked, see the log)";
    } else if (!g.target.exe.empty()) {
        wstring why;
        if (g.checks.firstFailure(g.force, why)) hint = why;
    }
    SetWindowTextW(GetDlgItem(g.hwnd, IDC_HINT), hint.c_str());
    UpdateButtons();
    InvalidateRect(g.hwnd, nullptr, FALSE);
}

