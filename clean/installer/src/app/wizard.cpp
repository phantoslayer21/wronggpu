void OnCollect() {
    wstring dir = g.target.dir;
    try {
        Bundle b = CollectLogs(g.ctx, dir, DefaultBundlePath(dir), g.sys);
        MessageBoxW(g.hwnd, BundleMessage(b).c_str(), L"Logs collected", MB_ICONINFORMATION);
        wstring args = L"/select,\"" + b.zip + L"\"";
        ShellExecuteW(nullptr, L"open", L"explorer.exe", args.c_str(), nullptr, SW_SHOWNORMAL);
    } catch (const SetupError& e) { MessageBoxW(g.hwnd, e.msg.c_str(), kAppName, MB_ICONWARNING); }
}

void OnNext() {
    switch (g.page) {
        case PG_WELCOME: ShowPage(PG_ROUTE); break;
        case PG_ROUTE: if (wg_wizard::RouteReady(g.route, g.ctx.opti.ok())) ShowPage(PG_GAME); break;
        case PG_GAME: RefreshChecks(); if (wg_wizard::RouteReady(g.route, g.ctx.opti.ok()) && g.checks.ok(g.force)) ShowPage(PG_REVIEW); break;
        case PG_REVIEW: case PG_UCONFIRM: BeginInstallOrUninstall(); break;
        case PG_FINISH:
            if (g.finishOk && !g.uninstall && SendMessageW(g.chkOpen, BM_GETCHECK, 0, 0) == BST_CHECKED) ShellExecuteW(nullptr, L"open", g.target.dir.c_str(), nullptr, nullptr, SW_SHOWNORMAL);
            DestroyWindow(g.hwnd);
            break;
        default: break;
    }
}
void OnBack() { if (g.page == PG_ROUTE) ShowPage(PG_WELCOME); else if (g.page == PG_GAME) ShowPage(PG_ROUTE); else if (g.page == PG_REVIEW) ShowPage(PG_GAME); }
void OnCancel() {
    if (g.working) return;
    if (MessageBoxW(g.hwnd, g.uninstall ? L"Exit without uninstalling?" : L"Exit the installer? Nothing has been changed yet.", kAppName, MB_YESNO | MB_ICONQUESTION | MB_DEFBUTTON2) == IDYES) DestroyWindow(g.hwnd);
}

