    const int n = g.uninstall ? 3 : 6;
    int cur = 0;
    for (int i = 0; i < n; ++i) if (steps[i].page == g.page) cur = i;
    const bool failed = g.page == PG_FINISH && !g.finishOk;
    const int logoW = 148, logoH = g.kit.logo ? (int)(148.0 * g.kit.logo->GetHeight() / std::max(1u, g.kit.logo->GetWidth())) : 0;
