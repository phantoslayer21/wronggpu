void StartWork() {
    g.working = true;
    ShowPage(PG_PROGRESS);
    SetWindowTextW(g.edLog, L"");
    GameTarget t = g.target; bool un = g.uninstall; HWND hwnd = g.hwnd; ModelState model = g.model;
    const HipInfo hip = g.sys.hip;
    Consent consent; consent.moveMods = consent.removeOld = NeedsConflictOk();
    const bool managed = !g.ctx.perGameEntry;  // the launcher is installed: the game goes on its list (its entry covers it)
    std::thread([t, un, hwnd, model, consent, hip, managed] {
        Ui ui;
        ui.step = [hwnd](int d, int n, const wstring& s) { PostMessageW(hwnd, WM_APP_STEP, 0, (LPARAM) new StepMsg{d, n, s}); };
        ui.log = [hwnd](const wstring& s) { LogLine(g.ctx, s); PostMessageW(hwnd, WM_APP_STEP, 1, (LPARAM) new StepMsg{0, 0, s}); };
        auto* done = new DoneMsg{false, L"", {}};
        try {
            CoInitializeEx(nullptr, COINIT_MULTITHREADED);
            done->warnings = un ? DoRestore(g.ctx, t.dir, ui, false, false) : DoInstall(g.ctx, t, model, consent, ui, hip);
            if (!un && managed) AddManagedGame(t.dir);
            done->ok = true;
        } catch (const SetupError& e) { done->text = e.msg; LogLine(g.ctx, L"ERROR: " + e.msg); }
        catch (...) { done->text = L"Unexpected error."; }
        PostMessageW(hwnd, WM_APP_DONE, 0, (LPARAM)done);
    }).detach();
}

bool RelaunchElevated() {
    wstring args = L"\"/EXE=" + g.target.exe + L"\" /GO /ELEVATED";
    if (g.uninstall) args = L"\"/DIR=" + g.target.dir + L"\" /GO /ELEVATED /UNINSTALL";
    if (!g.uninstall) {
        const wstring routeArgs = wg_wizard::RouteArguments(g.route, g.ctx.opti.source);
        if (routeArgs.empty()) return false;
        args += routeArgs;
    }
#if WRONGGPU_PRESET_K
    args += g.ctx.presetK ? L" /PRESET=K" : L" /PRESET=M";
#else
    args += L" /PRESET=M";
#endif
    if (g.force) args += L" /FORCE";
    if (!g.uninstall && NeedsConsent()) args += L" /EXPERIMENTAL";        // the player ticked the confirmation already
    if (!g.uninstall && NeedsConflictOk()) args += L" /MOVEMODS /REMOVEOLD";
    if (!g.uninstall && g.model.ok() && !g.model.reused) args += L" \"/MODEL=" + g.model.dll + L"\"";
    wstring self = SelfPath();
    SHELLEXECUTEINFOW sei{}; sei.cbSize = sizeof(sei); sei.lpVerb = L"runas"; sei.lpFile = self.c_str();
    sei.lpParameters = args.c_str(); sei.nShow = SW_SHOWNORMAL; sei.hwnd = g.hwnd;
    return ShellExecuteExW(&sei) != FALSE;
}

void BeginInstallOrUninstall() {
    if (!g.uninstall && !wg_wizard::RouteReady(g.route, g.ctx.opti.ok())) {
        ShowPage(PG_ROUTE);
        return;
    }
    if (!g.elevatedRelaunch && !IsElevated()) {
        DWORD e = WriteTest(g.target.dir);
        if (e == ERROR_ACCESS_DENIED || e == ERROR_WRITE_PROTECT) {
            if (RelaunchElevated()) { DestroyWindow(g.hwnd); return; }
            MessageBoxW(g.hwnd, L"Administrator permission is needed to change this game folder and was not granted.", kAppName, MB_ICONWARNING);
            return;
        }
    }
    StartWork();
}

bool BrowseFor(HWND owner, int mode, wstring& out) {
    const bool folder = mode == 1 || mode == 4;
    IFileOpenDialog* d = nullptr;
    if (FAILED(CoCreateInstance(CLSID_FileOpenDialog, nullptr, CLSCTX_INPROC_SERVER, IID_IFileOpenDialog, (void**)&d))) return false;
    DWORD o = 0; d->GetOptions(&o); d->SetOptions(o | FOS_FORCEFILESYSTEM | (folder ? FOS_PICKFOLDERS : FOS_FILEMUSTEXIST));
    if (folder) d->SetTitle(mode == 4 ? L"Select your unpacked OptiScaler folder" : L"Select the game's folder");
    else if (mode == 2) {
        COMDLG_FILTERSPEC spec[] = {{L"DLSS model file (nvngx_dlss.dll)", L"nvngx_dlss.dll"}, {L"DLL files (*.dll)", L"*.dll"}};
        d->SetFileTypes(2, spec);
        d->SetTitle(L"Select an nvngx_dlss.dll of version 310.5 or newer");
    } else if (mode == 3) {
        COMDLG_FILTERSPEC spec[] = {{L"OptiScaler release (*.7z, *.zip) or its OptiScaler.dll", L"*.7z;*.zip;OptiScaler.dll"}};
        d->SetFileTypes(1, spec);
        d->SetTitle((L"Select your OptiScaler download (tested: " + std::wstring(kOptiTested) + L")").c_str());
    } else {
        COMDLG_FILTERSPEC spec[] = {{L"Game executable (*.exe)", L"*.exe"}};
        d->SetFileTypes(1, spec);
        d->SetTitle(L"Select the game's .exe");
    }
    bool ok = false;
    if (SUCCEEDED(d->Show(owner))) {
        IShellItem* it = nullptr;
        if (SUCCEEDED(d->GetResult(&it))) { PWSTR p = nullptr; if (SUCCEEDED(it->GetDisplayName(SIGDN_FILESYSPATH, &p))) { out = p; CoTaskMemFree(p); ok = true; } it->Release(); }
    }
    d->Release();
    return ok;
}

