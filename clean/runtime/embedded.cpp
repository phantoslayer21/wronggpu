#include "embedded.h"

#include <cstddef>
#include <cstdint>
#include <cstdio>

namespace wg_embedded {
struct File {
  const char* name;
  const unsigned char* data;  // scrambled (see unscramble)
  size_t size;
};
#ifdef WG_EMBEDDED_TABLE
extern const File kFiles[];  // generated by clean/runner/build.py (embedded_files.cpp)
extern const size_t kCount;
#else
const File kFiles[] = {{nullptr, nullptr, 0}};  // a library without built-in files (tests, emulator)
const size_t kCount = 0;
#endif
}  // namespace wg_embedded

namespace {

const uint64_t kKey = 0x5747454D42454444ull;  // "WGEMBEDD"; the same in build.py

std::string base_name(const std::string& path) {
  const size_t p = path.find_last_of("/\\");
  return p == std::string::npos ? path : path.substr(p + 1);
}

uint64_t fnv1a(const std::string& s) {
  uint64_t h = 1469598103934665603ull;
  for (unsigned char c : s) h = (h ^ c) * 1099511628211ull;
  return h;
}

// XOR with an xorshift64* keystream seeded by the file name (not encryption: it only keeps the files from being
// stored as plain, carvable copies).
void unscramble(const std::string& name, const unsigned char* in, size_t n, char* out) {
  uint64_t x = kKey ^ fnv1a(name);
  if (!x) x = 1;
  for (size_t i = 0; i < n; i += 8) {
    x ^= x >> 12;
    x ^= x << 25;
    x ^= x >> 27;
    const uint64_t k = x * 0x2545F4914F6CDD1Dull;
    for (size_t b = 0; b < 8 && i + b < n; ++b) out[i + b] = (char)(in[i + b] ^ (unsigned char)(k >> (8 * b)));
  }
}

const wg_embedded::File* find(const std::string& path) {
  const std::string name = base_name(path);
  for (size_t i = 0; i < wg_embedded::kCount; ++i)
    if (name == wg_embedded::kFiles[i].name) return &wg_embedded::kFiles[i];
  return nullptr;
}

bool read_disk(const std::string& path, std::vector<char>* out) {
  std::FILE* fp = std::fopen(path.c_str(), "rb");
  if (!fp) return false;
  out->clear();
  char buf[65536];
  size_t n;
  while ((n = std::fread(buf, 1, sizeof(buf), fp)) > 0) out->insert(out->end(), buf, buf + n);
  std::fclose(fp);
  return true;
}

}  // namespace

bool wg_read_file(const std::string& path, std::vector<char>* out) {
  if (read_disk(path, out)) return true;
  const wg_embedded::File* f = find(path);
  if (!f) return false;
  out->resize(f->size);
  if (f->size) unscramble(f->name, f->data, f->size, out->data());
  return true;
}

bool wg_file_exists(const std::string& path) {
  if (std::FILE* fp = std::fopen(path.c_str(), "rb")) {
    std::fclose(fp);
    return true;
  }
  return find(path) != nullptr;
}
