"""Frame generation (issue #96): writes the two generated headers of the C++ FG runtime (clean/fg/runtime).

    python clean/fg/tools/gen_fg_runtime_tables.py            # rewrite both headers
    python clean/fg/tools/gen_fg_runtime_tables.py --check    # exit 1 when a header is not current

- clean/fg/runtime/fg_map_table.h: the 42 stages of data/fg.v1.map.json (17 net1 + 25 net2 layers, natural order) with
  their tensor shapes, sources and stage digests, plus the SHA-256 of the map file itself. The runtime checks a local
  model file against this table (fg_model.h).
- clean/fg/runtime/tests/net1_plan_golden.h: the fused net1 plan of clean/fg/runner/fg_net1_mma.py (plan_fused, 11
  launches) at several cell grids: every buffer in the replay's allocation order with its byte size, every launch with
  its kernel, grid and arguments. Also the weight fragments (swizzle) of every net1 layer for constructed float16 bit
  patterns (synth_bits below), as length and SHA-256. The C++ plan and packer are checked against it byte for byte.

Only shapes and constructed values: no model data is read or written.
"""
import argparse
import hashlib
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "clean", "fg", "runner"))

from clean.fg import layout as L  # noqa: E402
from clean.fg.reference import net1 as N  # noqa: E402
import fg_net1_mma as M  # noqa: E402

MAP = os.path.join(ROOT, "data", "fg.v1.map.json")
MAP_TABLE = os.path.join(ROOT, "clean", "fg", "runtime", "fg_map_table.h")
GOLDEN = os.path.join(ROOT, "clean", "fg", "runtime", "tests", "net1_plan_golden.h")

# net1 cell grids (H0, W0): the size table's rows for 1280x720, 1920x1080 (and 3840x2160), 2560x1440, 3440x1440 and
# 7680x4320 (FG-PART3 section 1.3), the replay's 64 x 64 pixel case and a grid whose levels do not halve exactly.
CASES = [(192, 320), (288, 480), (384, 640), (384, 864), (544, 960), (32, 32), (35, 45)]


def synth_bits(n):
    """Constructed float16 bit patterns for element i of a canonical weight tensor: finite, both signs, |x| < 2."""
    i = np.arange(n, dtype=np.uint64)
    return (((i * np.uint64(40503) + np.uint64(12345)) & np.uint64(0x3FFF)) |
            ((i & np.uint64(1)) << np.uint64(15))).astype(np.uint16)


def canonical_shape(layer):
    k = 3 if layer.taps == 9 else 1
    return (layer.out, k, k, layer.cin)


def zero_params():
    return {l.name: (np.zeros(canonical_shape(l), np.float16), np.zeros(l.out, np.float16)) for l in L.NET1}


def header(lines, what):
    return ["// SPDX-License-Identifier: MIT",
            "// GENERATED by clean/fg/tools/gen_fg_runtime_tables.py from %s; do not edit." % what,
            "// python clean/fg/tools/gen_fg_runtime_tables.py rewrites it, --check verifies it (clean/fg/tests).",
            "#pragma once", ""] + lines


def map_table():
    with open(MAP, "rb") as f:
        raw = f.read()
    m = json.loads(raw.decode("utf-8"))
    out = ["#include <cstdint>", "", "namespace wgfg {", "",
           "// SHA-256 of data/fg.v1.map.json as stored (the converter writes it into a model file's header).",
           'inline constexpr const char* kFgMapSha256 = "%s";' % hashlib.sha256(raw).hexdigest(),
           "inline constexpr uint32_t kFgMapStages = %d;" % len(m["stages"]), "",
           "struct FgMapStage {",
           "    const char* name;        // dl1.lNN (net1) or dl2.lNN (net2)",
           "    uint32_t w_rank;         // 4: [out, in, 3, 3]; 2: [out, in] (1 x 1)",
           "    uint32_t w_shape[4];",
           "    uint32_t b_len;",
           "    const char* w_source;",
           "    uint32_t w_source_bytes;",
           "    const char* b_source;",
           "    uint32_t b_source_bytes;",
           "    const char* digest;      // keyed SHA-256 of the stage's tensors (hex)",
           "};", "",
           "inline constexpr FgMapStage kFgMapTable[%d] = {" % len(m["stages"])]
    for s in m["stages"]:
        t = {x["name"]: x for x in s["tensors"]}
        w, b = t["W"], t["b"]
        dims = list(w["shape"]) + [0] * (4 - len(w["shape"]))
        out.append('    {"%s", %d, {%s}, %d, "%s", %d, "%s", %d, "%s"},' % (
            s["stage"], len(w["shape"]), ", ".join(str(d) for d in dims), b["shape"][0], w["src"],
            m["sources"][w["src"]]["length"], b["src"], m["sources"][b["src"]]["length"], s["digest"]))
    out += ["};", "", "}  // namespace wgfg", ""]
    return "\n".join(header(out, "data/fg.v1.map.json"))


def golden():
    params = zero_params()
    out = ["#include <cstdint>", "", "namespace wgfg_golden {", "",
           "struct Arg { const char* buf; uint32_t value; };  // buf: a buffer's arena offset; null: the value",
           "struct Step { const char* kernel; uint32_t grid; uint32_t nargs; Arg args[15]; uint32_t nouts; "
           "const char* outs[2]; };",
           "struct Buffer { const char* name; uint64_t bytes; };",
           "struct Case { uint32_t H0, W0; uint32_t nsteps; const Step* steps; uint32_t nbufs; const Buffer* bufs; };",
           "struct Pack { const char* layer; const char* order; uint64_t bytes; const char* sha256; };", ""]
    names = []
    for H0, W0 in CASES:
        data, acts, steps = M.plan_fused(H0, W0, params)
        tag = "c%dx%d" % (H0, W0)
        cells = 2 * H0 * W0 * N.CELL
        bufs = [("cells", cells)] + [(k, len(v)) for k, v in data.items()] + [(k, n) for k, (_, n) in acts.items()]
        out.append("inline constexpr Buffer %s_bufs[] = {" % tag)
        out += ['    {"%s", %d},' % (k, n) for k, n in bufs]
        out.append("};")
        out.append("inline constexpr Step %s_steps[] = {" % tag)
        for kernel, grid, args, outs, _ in steps:
            a = ", ".join('{"%s", 0}' % x[1:] if isinstance(x, str) else "{nullptr, %du}" % x for x in args)
            o = ", ".join('"%s"' % x for x in outs) + (", nullptr" if len(outs) == 1 else "")
            out.append('    {"%s", %d, %d, {%s}, %d, {%s}},' % (kernel, grid, len(args), a, len(outs), o))
        out.append("};")
        names.append((H0, W0, tag, len(steps), len(bufs)))
    out.append("inline constexpr Case kCases[] = {")
    out += ["    {%d, %d, %d, %s_steps, %d, %s_bufs}," % (H0, W0, ns, tag, nb, tag) for H0, W0, tag, ns, nb in names]
    out += ["};", ""]
    out.append("// swizzle() of every net1 layer for canonical weights [out, k, k, in] whose element i has the float16 "
               "bits")
    out.append("// ((i * 40503 + 12345) & 0x3FFF) | ((i & 1) << 15).")
    out.append("inline constexpr Pack kPacks[] = {")
    for l in L.NET1:
        shape = canonical_shape(l)
        w = synth_bits(int(np.prod(shape))).view(np.float16).reshape(shape)
        order = N.LAYER_CHUNKS.get(l.name, "ascending")
        b = M.swizzle(w, order)
        out.append('    {"%s", "%s", %d, "%s"},' % (l.name, order, len(b), hashlib.sha256(b).hexdigest()))
    out += ["};", "", "}  // namespace wgfg_golden", ""]
    return "\n".join(header(out, "clean/fg/runner/fg_net1_mma.py (plan_fused, swizzle)"))


def outputs():
    return {MAP_TABLE: map_table(), GOLDEN: golden()}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    stale = []
    for path, text in outputs().items():
        have = None
        if os.path.exists(path):
            with open(path, "rb") as f:
                have = f.read().decode("utf-8")
        if a.check:
            if have != text:
                stale.append(os.path.relpath(path, ROOT))
        elif have != text:
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
    if stale:
        print("not current: " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
